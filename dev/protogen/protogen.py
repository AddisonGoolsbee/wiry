# registration edits


def splice(text: str, tag: str, body: str) -> str:
    begin, end = f"// protogen:{tag} begin", f"// protogen:{tag} end"
    pat = re.compile(
        r"([ \t]*)" + re.escape(begin) + r".*?[ \t]*" + re.escape(end), re.S
    )
    m = pat.search(text)
    if not m:
        raise SpecError(f"marker {tag!r} not found in the target file")
    indent = m.group(1)
    lines = [indent + begin]
    for line in body.splitlines():
        lines.append((indent + line).rstrip() if line else "")
    lines.append(indent + end)
    return pat.sub(lambda _: "\n".join(lines), text, count=1)


def render_registration(specs: list[dict]) -> dict[Path, list[tuple[str, str]]]:
    ids = "\n".join(
        f"pub const {s['id']}: ProtoId = ProtoId({s['num']});"
        for s in sorted(specs, key=lambda s: s["num"])
    )
    builtins = "\n".join(
        f"ProtoId::{s['id']}," for s in sorted(specs, key=lambda s: s["num"])
    )
    descs = "\n".join(
        f"t[ProtoId::{s['id']}.0 as usize] = &{s['module']}::DESC;"
        for s in sorted(specs, key=lambda s: s["num"])
    )
    acc = []
    for s in sorted(specs, key=lambda s: s["num"]):
        if s.get("accessors"):
            names = ", ".join(rs_str(a) for a in s["accessors"])
            acc.append(f"ProtoId::{s['id']} => &[{names}],")
    parsed = []
    groups = []
    for s in sorted(specs, key=lambda s: s["num"]):
        if s.get("parsed_field"):
            parsed.append(f"ProtoId::{s['id']} => {rs_str(s['parsed_field'])},")
        if s.get("group"):
            groups.append(
                f"ProtoId::{s['id']} => Some(&crate::layers::{s['module']}::GROUP),"
            )
    mods = "\n".join(
        f"pub mod {m};"
        for m in sorted({s["module"] for s in specs} | {"dispatch"})
    )
    return {
        PROTO_RS: [
            ("ids", ids),
            ("builtins", builtins),
            ("desc", descs),
            ("accessors", "\n".join(acc)),
            ("parsed", "\n".join(parsed)),
            ("groups", "\n".join(groups)),
        ],
        MOD_RS: [("mods", mods)],
    }


