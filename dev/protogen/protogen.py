# dispatch table


def render_dispatch(specs: list[dict]) -> str:
    by_kind: dict[str, list[tuple[dict, dict]]] = {k: [] for k in PARENT_KINDS}
    for s in specs:
        for p in s.get("parents", []):
            by_kind[p["from"]].append((s, p))

    out = [
        "//! Where every generated layer is reached from, and what to write back",
        "//! when one is stacked. Values come from the IANA registry or the RFC",
        "//! cited in each layer's module.",
        "//!",
        "//! " + BANNER.format(spec="*.toml"),
        "",
        "use crate::proto::ProtoId;",
        "",
    ]

    if any(by_kind[k] for k in PARENT_KINDS if k.endswith("_port")):
        out += [
            "const fn port_bits<const N: usize>(ports: &[u16]) -> [u64; N] {",
            "    let mut bits = [0u64; N];",
            "    let mut i = 0;",
            "    while i < ports.len() {",
            "        bits[(ports[i] >> 6) as usize] |= 1u64 << (ports[i] & 63);",
            "        i += 1;",
            "    }",
            "    bits",
            "}",
            "",
            "/// The table is sized to the largest claimed port, so a port past its end",
            "/// is unclaimed by construction.",
            "#[inline]",
            "fn claimed(bits: &[u64], v: u16) -> bool {",
            "    let i = (v >> 6) as usize;",
            "    i < bits.len() && bits[i] & (1u64 << (v & 63)) != 0",
            "}",
            "",
        ]

    def arms_for(entries, guarded: bool) -> list[str]:
        """Two protocols may share a selector — NetFlow v5, v9 and IPFIX all
        arrive on UDP 2055 — so candidates are grouped by value and each one's
        guard decides in turn."""
        by_value: dict[int, list[tuple[dict, dict]]] = {}
        for s, p in entries:
            for v in p["values"]:
                by_value.setdefault(v, []).append((s, p))
        groups: dict[tuple, list[int]] = {}
        for v in sorted(by_value):
            key = tuple((s["id"], p.get("guard")) for s, p in by_value[v])
            groups.setdefault(key, []).append(v)
        arms = []
        for key, vals in sorted(groups.items(), key=lambda kv: kv[1][0]):
            pat = " | ".join(str(v) for v in vals)
            cands = [
                (pid, g if guarded else None) for pid, g in key
            ]
            if len(cands) == 1 and cands[0][1] is None:
                arms.append(f"        {pat} => Some(ProtoId::{cands[0][0]}),")
            elif len(cands) == 1:
                arms.append(
                    f"        {pat} => {cands[0][1]}(payload)"
                    f".then_some(ProtoId::{cands[0][0]}),"
                )
            else:
                arms.append(f"        {pat} => {{")
                for pid, guard in cands:
                    if guard:
                        arms.append(f"            if {guard}(payload) {{")
                        arms.append(f"                return Some(ProtoId::{pid});")
                        arms.append("            }")
                    else:
                        arms.append(f"            Some(ProtoId::{pid})")
                if all(g for _, g in cands):
                    arms.append("            None")
                arms.append("        }")
        return arms

    tests: list[str] = []
    gates: list[tuple[str, str]] = []

    for kind, (fname, ty) in PARENT_KINDS.items():
        entries = by_kind[kind]
        is_port = kind.endswith("_port")
        if not entries:
            body = "    None\n"
            if is_port:
                out.append("#[inline]")
                out.append(
                    f"pub fn {fname}(_sport: {ty}, _dport: {ty}, _payload: &[u8])"
                    " -> Option<ProtoId> {"
                )
            else:
                out.append("#[inline]")
                out.append(f"pub fn {fname}(_v: {ty}) -> Option<ProtoId> {{")
            out.append(body.rstrip())
            out.append("}")
            out.append("")
            continue

        if is_port:
            if ty != "u16":
                raise SpecError(f"{kind}: the port bitmap is u16-only")
            inner = f"{fname}_one"
            values = f"{kind.upper()}_VALUES"
            bits = f"{kind.upper()}_CLAIMED"
            arms = arms_for(entries, True)
            used = any("payload" in a for a in arms)
            ports = sorted({v for _, p in entries for v in p["values"]})
            out += [
                f"const {values}: &[u16] = &[" + ", ".join(str(v) for v in ports) + "];",
                "",
                f"static {bits}: [u64; {(ports[-1] >> 6) + 1}] = port_bits({values});",
                "",
                "// Out of line: almost no traffic claims a layer here, so the match",
                "// must not weigh on the callers that never reach it.",
                "#[inline(never)]",
                f"fn {inner}(v: {ty}, {'payload' if used else '_payload'}: &[u8])"
                " -> Option<ProtoId> {",
                "    match v {",
                *arms,
                "        _ => None,",
                "    }",
                "}",
                "",
                "/// The destination port names the service, so it is asked first.",
                "#[inline]",
                f"pub fn {fname}(sport: {ty}, dport: {ty}, payload: &[u8])"
                " -> Option<ProtoId> {",
                f"    if !claimed(&{bits}, dport) && !claimed(&{bits}, sport) {{",
                "        return None;",
                "    }",
                f"    {inner}(dport, payload).or_else(|| {inner}(sport, payload))",
                "}",
                "",
            ]
            tests += [
                "    #[test]",
                f"    fn {kind}_bitmap_agrees_with_the_match() {{",
                f"        for v in 0..={ty}::MAX {{",
                f"            let c = super::claimed(&super::{bits}, v);",
                f"            assert_eq!(c, super::{values}.contains(&v), \"{kind} {{v}}\");",
                "            for p in PROBES {",
                f"                assert!(c || super::{inner}(v, p).is_none(),",
                f"                    \"{kind} {{v}} dispatches past the bitmap\");",
                "            }",
                "        }",
                "    }",
                "",
            ]
        else:
            out.append("#[inline]")
            out.append(f"pub fn {fname}(v: {ty}) -> Option<ProtoId> {{")
            out.append("    match v {")
            out.extend(arms_for(entries, False))
            out.append("        _ => None,")
            out.append("    }")
            out.append("}")
            out.append("")

        # Reverse direction: stacking a layer writes the parent's selector.
        rev = [
            (s, p)
            for s, p in entries
            if p.get("bind", p["values"][0]) is not False
        ]
        if rev:
            out.append("#[inline]")
            out.append(f"pub fn {fname}_of(p: ProtoId) -> Option<{ty}> {{")
            out.append("    match p {")
            seen = set()
            for s, p in rev:
                if s["id"] in seen:
                    continue
                seen.add(s["id"])
                v = p.get("bind", p["values"][0])
                out.append(f"        ProtoId::{s['id']} => Some({v}),")
            out.append("        _ => None,")
            out.append("    }")
            out.append("}")
            out.append("")
            if is_port:
                gates.append((fname, f"{kind.upper()}_CLAIMED"))
    if gates:
        tests += [
            "    /// The reverse map is what stacking a layer writes, so a port it",
            "    /// names that the gate does not claim would build a packet the",
            "    /// dissector cannot read back.",
            "    #[test]",
            "    fn every_bound_port_is_still_claimed() {",
            "        for id in crate::proto::builtins() {",
            *[
                f"            if let Some(v) = super::{fname}_of(id) {{\n"
                f"                assert!(super::claimed(&super::{bits}, v),"
                f' "{fname} {{v}}");\n'
                "            }"
                for fname, bits in gates
            ],
            "        }",
            "    }",
            "",
        ]
    if tests:
        out += [
            "#[cfg(test)]",
            "mod tests {",
            "    /// A guard that rejects every probe would hide a dropped bitmap bit,",
            "    /// so the probes have to reach as many arms as they can.",
            "    const PROBES: &[&[u8]] = &[",
            "        &[],",
            "        &[0u8; 64],",
            "        &[0xff; 64],",
            "        b\"GET / HTTP/1.1\\r\\nHost: h\\r\\n\\r\\n\",",
            "    ];",
            "",
            *tests,
            "}",
        ]
    return "\n".join(out).rstrip() + "\n"


