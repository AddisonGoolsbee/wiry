    fn dissects_the_rfc_vector() {
        let p = Packet::dissect(vector(), ProtoId::NetflowV5);
        let l = p.find_layer(ProtoId::NetflowV5).unwrap();
        assert_eq!(p.get(l, "version").unwrap(), FieldValue::Uint(5));
        assert_eq!(p.get(l, "count").unwrap(), FieldValue::Uint(1));
        assert_eq!(p.get(l, "sysUptime").unwrap(), FieldValue::Uint(1000));
        assert_eq!(p.get(l, "unixSecs").unwrap(), FieldValue::Uint(0));
        assert_eq!(p.get(l, "unixNanoSeconds").unwrap(), FieldValue::Uint(0));
        assert_eq!(p.get(l, "flowSequence").unwrap(), FieldValue::Uint(0));
        assert_eq!(p.get(l, "engineType").unwrap(), FieldValue::Uint(0));
        assert_eq!(p.get(l, "engineID").unwrap(), FieldValue::Uint(0));
        assert_eq!(p.get(l, "samplingInterval").unwrap(), FieldValue::Uint(0));
        assert_eq!(p.raw_bytes(), &vector()[..]);
    }

    #[test]
    fn truncation_does_not_panic() {
        for n in 0..vector().len() {
            let p = Packet::dissect(vector()[..n].to_vec(), ProtoId::NetflowV5);
            assert_eq!(p.raw_bytes(), &vector()[..n]);
        }
    }

    #[test]
    fn writes_survive_a_rebuild() {
        let mut p = Packet::dissect(vector(), ProtoId::NetflowV5);
        let l = p.find_layer(ProtoId::NetflowV5).unwrap();
        let n = p.raw_bytes().len();
        for f in crate::proto::active_fields(ProtoId::NetflowV5, false, p.header(l))
            .filter(|f| f.kind == crate::field::FieldKind::Uint && f.bit_len <= 32)
            .map(|f| f.name)
            .collect::<Vec<_>>()
        {
            p.set_uint(l, f, 1);
        }
        assert_eq!(p.to_bytes().len(), n);
    }
