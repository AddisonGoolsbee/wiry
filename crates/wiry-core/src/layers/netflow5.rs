#[cfg(test)]
mod tests {
    #![allow(unused_imports)]
    use super::*;
    use crate::field::FieldValue;
    use crate::packet::Packet;

    // protogen:tests begin
    /// Cisco NetFlow v5 export header, hand-built: version 5, one record, uptime 1000 ms.
    fn vector() -> Vec<u8> {
        vec![
            0x00, 0x05, 0x00, 0x01, 0x00, 0x00, 0x03, 0xe8, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
            0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        ]
    }

    #[test]
    fn dissects_the_rfc_vector() {
        let p = Packet::dissect(vector(), ProtoId::NetflowV5);
        let l = p.find_layer(ProtoId::NetflowV5).unwrap();
        assert_eq!(p.get(l, "version").unwrap(), FieldValue::Uint(5));
        assert_eq!(p.get(l, "count").unwrap(), FieldValue::Uint(1));
        assert_eq!(p.get(l, "sysUptime").unwrap(), FieldValue::Uint(1000));
        assert_eq!(p.get(l, "unixSecs").unwrap(), FieldValue::Uint(0));
        assert_eq!(p.get(l, "unixNanoSeconds").unwrap(), FieldValue::Uint(0));
        assert_eq!(p.get(l, "flowSequence").unwrap(), FieldValue::Uint(0));
        assert_eq!(p.get(l, "engineType").unwrap(), FieldValue::Uint(0));
        assert_eq!(p.get(l, "engineID").unwrap(), FieldValue::Uint(0));
        assert_eq!(p.get(l, "samplingInterval").unwrap(), FieldValue::Uint(0));
        assert_eq!(p.raw_bytes(), &vector()[..]);
    }

    #[test]
    fn truncation_does_not_panic() {
        for n in 0..vector().len() {
            let p = Packet::dissect(vector()[..n].to_vec(), ProtoId::NetflowV5);
            assert_eq!(p.raw_bytes(), &vector()[..n]);
        }
    }

    #[test]
    fn writes_survive_a_rebuild() {
        let mut p = Packet::dissect(vector(), ProtoId::NetflowV5);
        let l = p.find_layer(ProtoId::NetflowV5).unwrap();
        let n = p.raw_bytes().len();
        for f in crate::proto::active_fields(ProtoId::NetflowV5, false, p.header(l))
            .filter(|f| f.kind == crate::field::FieldKind::Uint && f.bit_len <= 32)
            .map(|f| f.name)
            .collect::<Vec<_>>()
        {
            p.set_uint(l, f, 1);
        }
        assert_eq!(p.to_bytes().len(), n);
    }

    use crate::options::ItemValue;

    fn record(src: [u8; 4], dst: [u8; 4], pkts: u32) -> Vec<u8> {
        let mut v = src.to_vec();
        v.extend_from_slice(&dst);
        v.resize(12, 0);
        v.extend_from_slice(&[0, 0, 0, 0]);
        v.extend_from_slice(&pkts.to_be_bytes());
        v.resize(48, 0);
        v
    }

    fn export(claimed: u16, n: usize) -> Vec<u8> {
        let mut v = vec![0u8, 5];
        v.extend_from_slice(&claimed.to_be_bytes());
        v.resize(24, 0);
        for i in 0..n {
            v.extend(record([1, 2, 3, i as u8], [5, 6, 7, 8], i as u32 + 1));
        }
        v
    }

    fn field_of<'a>(items: &'a [crate::options::Item], i: usize, name: &str) -> &'a ItemValue {
        let ItemValue::Items(v) = &items[i].value else {
            panic!("not a record")
        };
        &v.iter()
            .find(|f| f.name == name)
            .expect("named field")
            .value
    }

    #[test]
    fn the_count_field_drives_the_record_list() {
        let p = Packet::dissect(export(2, 2), ProtoId::NetflowV5);
        let l = p.find_layer(ProtoId::NetflowV5).unwrap();
        let items = p.options(l).unwrap();
        assert_eq!(items.len(), 2);
        assert_eq!(items[0].name, "NetflowRecordV5");
        assert_eq!(
            field_of(&items, 0, "src"),
            &ItemValue::Text("1.2.3.0".into())
        );
        assert_eq!(field_of(&items, 1, "dpkts"), &ItemValue::Uint(2));
    }

    /// A count that claims more records than the datagram carries must yield
    /// what arrived, not what was claimed.
    #[test]
    fn an_over_claimed_count_yields_only_what_arrived() {
        let p = Packet::dissect(export(0xffff, 2), ProtoId::NetflowV5);
        let l = p.find_layer(ProtoId::NetflowV5).unwrap();
        assert_eq!(p.options(l).unwrap().len(), 2);
    }

    /// The reverse: trailing octets past the claimed count are not records.
    #[test]
    fn a_short_count_stops_early() {
        let p = Packet::dissect(export(1, 3), ProtoId::NetflowV5);
        let l = p.find_layer(ProtoId::NetflowV5).unwrap();
        assert_eq!(p.options(l).unwrap().len(), 1);
    }

    #[test]
    fn records_encode_back_to_the_bytes_they_came_from() {
        let p = Packet::dissect(export(2, 2), ProtoId::NetflowV5);
        let l = p.find_layer(ProtoId::NetflowV5).unwrap();
        let items = p.options(l).unwrap();
        assert_eq!(
            crate::repeat::encode(&GROUP, &items).unwrap(),
            export(2, 2)[24..]
        );
    }
    // protogen:tests end
}
