//! Cisco Systems, "NetFlow Export Datagram Formats", version 5 header: a 16-bit
//! version (5), a 16-bit record count, the 32-bit system uptime in milliseconds,
//! the 32-bit UNIX seconds and nanoseconds of the export, a 32-bit flow sequence
//! number, a one-octet engine type, a one-octet engine id and a two-octet
//! sampling interval.
//!
//! The 48-octet flow records that follow are a count-driven repeating group
//! (`crates/wiry-core/src/repeat.rs`): `count` says how many, and the same document
//! gives the record as source, destination and next-hop addresses, SNMP input and
//! output indices, packet and octet counts, the first and last uptimes of the flow,
//! the port pair, a pad octet, the cumulative TCP flags, the IP protocol and type of
//! service, the source and destination autonomous systems, the two prefix mask
//! widths and two octets of padding. RFC 3954 defines version 9, not version 5; v5
//! has no RFC, so Cisco's document is the control.
//!
//! Generated by dev/protogen from dev/protogen/specs/netflow5.toml. Field layouts
//! come from the RFC cited above; edit the spec, not this file.

