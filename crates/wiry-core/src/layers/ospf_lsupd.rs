#[cfg(test)]
mod tests {
    #![allow(unused_imports)]
    use super::*;
    use crate::field::FieldValue;
    use crate::packet::Packet;

    // protogen:tests begin
    /// RFC 2328 §A.3.5 update, hand-built: one 20-octet router LSA for 10.0.0.1.
    fn vector() -> Vec<u8> {
        vec![
            0x00, 0x00, 0x00, 0x01, 0x00, 0x01, 0x02, 0x01, 0x0a, 0x00, 0x00, 0x01, 0x0a, 0x00,
            0x00, 0x01, 0x80, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x14,
        ]
    }

    #[test]
    fn dissects_the_rfc_vector() {
        let p = Packet::dissect(vector(), ProtoId::OspfLsUpd);
        let l = p.find_layer(ProtoId::OspfLsUpd).unwrap();
        assert_eq!(p.get(l, "lsacount").unwrap(), FieldValue::Uint(1));
        assert_eq!(p.raw_bytes(), &vector()[..]);
    }

    #[test]
    fn truncation_does_not_panic() {
        for n in 0..vector().len() {
            let p = Packet::dissect(vector()[..n].to_vec(), ProtoId::OspfLsUpd);
            assert_eq!(p.raw_bytes(), &vector()[..n]);
        }
    }

    #[test]
    fn writes_survive_a_rebuild() {
        let mut p = Packet::dissect(vector(), ProtoId::OspfLsUpd);
        let l = p.find_layer(ProtoId::OspfLsUpd).unwrap();
        let n = p.raw_bytes().len();
        for f in crate::proto::active_fields(ProtoId::OspfLsUpd, false, p.header(l))
            .filter(|f| f.kind == crate::field::FieldKind::Uint && f.bit_len <= 32)
            .map(|f| f.name)
            .collect::<Vec<_>>()
        {
            p.set_uint(l, f, 1);
        }
        assert_eq!(p.to_bytes().len(), n);
    }

    use crate::options::ItemValue;

    /// RFC 2328 §A.4.1: the element width is the LSA's own `len`, so a body
    /// longer than the 20-octet header still advances by the right amount.
    #[test]
    fn an_lsa_longer_than_its_header_advances_by_its_own_length() {
        let mut data = vec![0u8, 0, 0, 2];
        let mut first = vector()[4..].to_vec();
        first[19] = 24;
        data.extend(first);
        data.extend_from_slice(&[0, 0, 0, 0]);
        data.extend(vector()[4..].to_vec());
        let p = Packet::dissect(data, ProtoId::OspfLsUpd);
        let l = p.find_layer(ProtoId::OspfLsUpd).unwrap();
        let items = p.options(l).unwrap();
        assert_eq!(items.len(), 2);
        let ItemValue::Items(second) = &items[1].value else {
            panic!("not a record")
        };
        assert_eq!(second[7].value, ItemValue::Uint(20));
        let ItemValue::Items(first) = &items[0].value else {
            panic!("not a record")
        };
        assert_eq!(first[8].value, ItemValue::Bytes(vec![0, 0, 0, 0]));
    }

    /// A zero length cannot make progress, so the walk stops rather than
    /// spinning on it.
    #[test]
    fn an_lsa_claiming_no_length_stops_the_walk() {
        let p = Packet::dissect(vec![0u8, 0, 0, 1, 0, 0, 0, 0, 0, 0], ProtoId::OspfLsUpd);
        let l = p.find_layer(ProtoId::OspfLsUpd).unwrap();
        assert!(p.options(l).unwrap().is_empty());
    }

    #[test]
    fn the_count_is_rewritten_from_what_the_region_holds() {
        let mut data = vector();
        data[..4].copy_from_slice(&[0, 0, 0, 0]);
        data.extend(vector()[4..].to_vec());
        let mut p = Packet::dissect(data, ProtoId::OspfLsUpd);
        let l = p.find_layer(ProtoId::OspfLsUpd).unwrap();
        p.sync_group(l);
        assert_eq!(p.get(l, "lsacount").unwrap(), FieldValue::Uint(2));
    }
    // protogen:tests end
}
