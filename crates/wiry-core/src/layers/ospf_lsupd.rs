//! RFC 2328 §A.3.5, Link State Update packet: a 32-bit count of the LSAs that
//! follow, and then that many LSAs. §A.4.1 gives every LSA a common 20-octet
//! header whose last field is the LSA's own total length, so the count and that
//! length together make the body a count-driven repeating group of computed width
//! (`crates/wiry-core/src/repeat.rs`).
//!
//! The LSA header is read; the body past it is kept as octets under `lsa`, not
//! decoded. §A.4.2 onwards give each LS type a different layout, which the flat
//! record table cannot express — see DEVIATIONS E1. The 20-octet header is also
//! the floor `elem_min` sets, so an LSA whose `len` is smaller than its own header
//! neither stalls the walk nor makes the element overlap the one before it.
//!
