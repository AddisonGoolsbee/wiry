#[cfg(test)]
mod tests {
    #![allow(unused_imports)]
    use super::*;
    use crate::field::FieldValue;
    use crate::packet::Packet;

    // protogen:tests begin
    /// sFlow v5 §5.1 datagram, hand-built: agent 10.0.0.1, sequence 1, one four-octet counter sample (format 3).
    fn vector() -> Vec<u8> {
        vec![
            0x00, 0x00, 0x00, 0x05, 0x00, 0x00, 0x00, 0x01, 0x0a, 0x00, 0x00, 0x01, 0x00, 0x00,
            0x00, 0x00, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x03, 0xe8, 0x00, 0x00, 0x00, 0x01,
            0x00, 0x00, 0x00, 0x03, 0x00, 0x00, 0x00, 0x04, 0x0a, 0x0b, 0x0c, 0x0d,
        ]
    }

    #[test]
    fn dissects_the_rfc_vector() {
        let p = Packet::dissect(vector(), ProtoId::SFlow);
        let l = p.find_layer(ProtoId::SFlow).unwrap();
        assert_eq!(p.get(l, "version").unwrap(), FieldValue::Uint(5));
        assert_eq!(p.get(l, "agent_address_type").unwrap(), FieldValue::Uint(1));
        assert_eq!(p.get(l, "sub_agent_id").unwrap(), FieldValue::Uint(0));
        assert_eq!(p.get(l, "sequence_number").unwrap(), FieldValue::Uint(1));
        assert_eq!(p.get(l, "sysuptime").unwrap(), FieldValue::Uint(1000));
        assert_eq!(p.get(l, "num_samples").unwrap(), FieldValue::Uint(1));
        assert_eq!(p.raw_bytes(), &vector()[..]);
    }

    #[test]
    fn truncation_does_not_panic() {
        for n in 0..vector().len() {
            let p = Packet::dissect(vector()[..n].to_vec(), ProtoId::SFlow);
            assert_eq!(p.raw_bytes(), &vector()[..n]);
        }
    }

    #[test]
    fn writes_survive_a_rebuild() {
        let mut p = Packet::dissect(vector(), ProtoId::SFlow);
        let l = p.find_layer(ProtoId::SFlow).unwrap();
        let n = p.raw_bytes().len();
        for f in crate::proto::active_fields(ProtoId::SFlow, false, p.header(l))
            .filter(|f| f.kind == crate::field::FieldKind::Uint && f.bit_len <= 32)
            .map(|f| f.name)
            .collect::<Vec<_>>()
        {
            p.set_uint(l, f, 1);
        }
        assert_eq!(p.to_bytes().len(), n);
    }

    use crate::options::ItemValue;

    #[test]
    fn samples_read_at_the_width_their_own_length_claims() {
        let p = Packet::dissect(vector(), ProtoId::SFlow);
        let l = p.find_layer(ProtoId::SFlow).unwrap();
        let items = p.options(l).unwrap();
        assert_eq!(items.len(), 1);
        let ItemValue::Items(f) = &items[0].value else {
            panic!("not a record")
        };
        assert_eq!(f[0].value, ItemValue::Uint(3));
        assert_eq!(f[1].value, ItemValue::Uint(4));
        assert_eq!(f[2].value, ItemValue::Bytes(vec![0x0a, 0x0b, 0x0c, 0x0d]));
    }

    /// §5.1: an IPv6 agent address moves every field after it, so the samples
    /// are not where this group would look for them.
    #[test]
    fn an_ipv6_agent_datagram_reads_no_samples() {
        let mut data = vector();
        data[7] = 2;
        let p = Packet::dissect(data, ProtoId::SFlow);
        let l = p.find_layer(ProtoId::SFlow).unwrap();
        assert!(p.options(l).unwrap().is_empty());
    }

    #[test]
    fn samples_encode_back_to_the_bytes_they_came_from() {
        let p = Packet::dissect(vector(), ProtoId::SFlow);
        let l = p.find_layer(ProtoId::SFlow).unwrap();
        let items = p.options(l).unwrap();
        assert_eq!(
            crate::repeat::encode(&GROUP, &items).unwrap(),
            vector()[28..]
        );
    }
    // protogen:tests end
}
