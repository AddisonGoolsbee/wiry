/// §5.1: address type 2 is a 16-octet IPv6 agent address, which moves every
/// field after it — including the samples, which is why they are read only
/// for the IPv4 form.
fn is_ipv4_agent(hdr: &[u8]) -> bool {
    !matches!(hdr.get(4..8), Some(&[0, 0, 0, 2]))
}

fn header_len(hdr: &[u8]) -> usize {
    if !is_ipv4_agent(hdr) {
        return 40;
    }
    (28 + crate::repeat::region_len(hdr, &GROUP)).min(hdr.len())
}
