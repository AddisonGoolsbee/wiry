//! sFlow.org, "sFlow Version 5" (July 2004), §5.1 datagram format: a 32-bit
//! version (5), a 32-bit address type (1 IPv4, 2 IPv6), the agent address, a
//! 32-bit sub-agent id, a 32-bit datagram sequence number, the 32-bit agent
//! uptime in milliseconds and a 32-bit sample count. §5.1 then gives the samples
//! themselves: each is a 32-bit sample type (the enterprise number in the high 20
//! bits and the format in the low 12), a 32-bit length in octets and that many
//! octets of sample data, which is a count-driven repeating group of computed
//! width (`crates/wiry-core/src/repeat.rs`).
//!
//! The sample data is kept as octets: §5.1 gives each format its own record
//! structure, which the flat record table cannot express (DEVIATIONS E1). Only the
//! IPv4 agent-address form has a fixed header length, so an address type of 2
//! moves every field after it and its samples stay in the payload.
//!
//! Generated by dev/protogen from dev/protogen/specs/sflow.toml. Field layouts
//! come from the RFC cited above; edit the spec, not this file.

