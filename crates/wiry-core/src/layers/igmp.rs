#[cfg(test)]
mod tests {
    #![allow(unused_imports)]
    use super::*;
    use crate::field::FieldValue;
    use crate::packet::Packet;

    // protogen:tests begin
    /// RFC 2236 §2 membership report for 224.0.0.251, max response time 0.
    fn vector() -> Vec<u8> {
        vec![0x16, 0x00, 0x09, 0x04, 0xe0, 0x00, 0x00, 0xfb]
    }

    #[test]
    fn dissects_the_rfc_vector() {
        let p = Packet::dissect(vector(), ProtoId::Igmp);
        let l = p.find_layer(ProtoId::Igmp).unwrap();
        assert_eq!(p.get(l, "type").unwrap(), FieldValue::Uint(22));
        assert_eq!(p.get(l, "mrcode").unwrap(), FieldValue::Uint(0));
        assert_eq!(p.get(l, "chksum").unwrap(), FieldValue::Uint(2308));
        assert_eq!(p.raw_bytes(), &vector()[..]);
    }

    #[test]
    fn truncation_does_not_panic() {
        for n in 0..vector().len() {
            let p = Packet::dissect(vector()[..n].to_vec(), ProtoId::Igmp);
            assert_eq!(p.raw_bytes(), &vector()[..n]);
        }
    }

    #[test]
    fn writes_survive_a_rebuild() {
        let mut p = Packet::dissect(vector(), ProtoId::Igmp);
        let l = p.find_layer(ProtoId::Igmp).unwrap();
        let n = p.raw_bytes().len();
        for f in crate::proto::active_fields(ProtoId::Igmp, false, p.header(l))
            .filter(|f| f.kind == crate::field::FieldKind::Uint && f.bit_len <= 32)
            .map(|f| f.name)
            .collect::<Vec<_>>()
        {
            p.set_uint(l, f, 1);
        }
        assert_eq!(p.to_bytes().len(), n);
    }
    // protogen:tests end
}
