fn msg_type(hdr: &[u8]) -> u8 {
    hdr.first().copied().unwrap_or(0x11)
}

/// RFC 3376 §4.2 puts a reserved word and a record count where every other
/// version carries the group address.
fn is_v3_report(hdr: &[u8]) -> bool {
    msg_type(hdr) == 0x22
}

fn has_group_address(hdr: &[u8]) -> bool {
    !is_v3_report(hdr)
}

/// RFC 3376 §4.1: a version 3 query is a type 0x11 message of at least twelve
/// octets. Length is the only thing that tells it from a version 2 query.
fn is_v3_query(hdr: &[u8]) -> bool {
    msg_type(hdr) == 0x11 && hdr.len() >= 12
}

fn header_len(hdr: &[u8]) -> usize {
    // The group records belong to the header, because the walk is handed the
    // header and nothing else.
    if is_v3_report(hdr) {
        return (8 + crate::repeat::region_len(hdr, &GROUP)).min(hdr.len());
    }
    if !is_v3_query(hdr) {
        return 8;
    }
    let n = u16::from_be_bytes([hdr[10], hdr[11]]) as usize;
    (12 + n.min(4096) * 4).min(hdr.len())
}
