//! RFC 2236 §2 (IGMPv2) and RFC 1112 Appendix I (IGMPv1) give the same eight
//! octets: a one-octet type, a one-octet max response time, a 16-bit checksum and
//! a group address. RFC 3376 §4.1 keeps that prefix for a version 3 Membership
//! Query and appends a suppress/QRV octet, a QQIC octet and a source count; §4.2
//! replaces the group address with a reserved word and a group record count. The
//! three versions share one layer because they share one prefix and differ only in
//! what follows it, which is what a conditional field is for.
//!
//! RFC 3376 §4.2.4 makes the version 3 report's body a count-driven repeating
//! group (`crates/wiry-core/src/repeat.rs`): `numgrp` group records, each a record
//! type, an auxiliary-data length in 32-bit words, a source count, a multicast
//! address, and then that many source addresses — so a record is eight octets plus
//! four per source plus four per auxiliary word, and the sources are a nested
//! group of their own. The version 3 query's source list (§4.1.10) is inside the
//! header but is not decoded: a layer answers under one group. See DEVIATIONS E1.
//!
//! Generated by dev/protogen from dev/protogen/specs/igmp.toml. Field layouts
//! come from the RFC cited above; edit the spec, not this file.

