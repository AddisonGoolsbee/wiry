//! RFC 7011 §3.1: a 16-bit version (10), a 16-bit length covering the whole
//! message, a 32-bit export time in seconds, a 32-bit sequence number and a 32-bit
//! observation domain id. §3.3.2 gives every Set the same two leading fields — a
//! 16-bit Set id (2 template, 3 options template, 256 and up data) and a 16-bit
//! length covering both of them and the records — so the Sets are a repeating
//! group whose element width is its own length field
//! (`crates/wiry-core/src/repeat.rs`), running to the end of the message.
//!
//! The Set *contents* are not decoded: a data Set needs the template the exporter
//! sent in an earlier message, which is per-session state this dissector does not
//! keep (DEVIATIONS P6).
//!
//! Generated by dev/protogen from dev/protogen/specs/ipfix.toml. Field layouts
//! come from the RFC cited above; edit the spec, not this file.

