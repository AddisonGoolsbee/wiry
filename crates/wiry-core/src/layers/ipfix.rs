#[cfg(test)]
mod tests {
    #![allow(unused_imports)]
    use super::*;
    use crate::field::FieldValue;
    use crate::packet::Packet;

    // protogen:tests begin
    /// RFC 7011 §3.1 message, hand-built: version 10, sequence 1, one eight-octet template Set.
    fn vector() -> Vec<u8> {
        vec![
            0x00, 0x0a, 0x00, 0x18, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00,
            0x00, 0x00, 0x00, 0x02, 0x00, 0x08, 0x01, 0x00, 0x00, 0x01,
        ]
    }

    #[test]
    fn dissects_the_rfc_vector() {
        let p = Packet::dissect(vector(), ProtoId::Ipfix);
        let l = p.find_layer(ProtoId::Ipfix).unwrap();
        assert_eq!(p.get(l, "version").unwrap(), FieldValue::Uint(10));
        assert_eq!(p.get(l, "length").unwrap(), FieldValue::Uint(24));
        assert_eq!(p.get(l, "exportTime").unwrap(), FieldValue::Uint(0));
        assert_eq!(p.get(l, "sequenceNumber").unwrap(), FieldValue::Uint(1));
        assert_eq!(
            p.get(l, "observationDomainID").unwrap(),
            FieldValue::Uint(0)
        );
        assert_eq!(p.raw_bytes(), &vector()[..]);
    }

    #[test]
    fn truncation_does_not_panic() {
        for n in 0..vector().len() {
            let p = Packet::dissect(vector()[..n].to_vec(), ProtoId::Ipfix);
            assert_eq!(p.raw_bytes(), &vector()[..n]);
        }
    }

    #[test]
    fn writes_survive_a_rebuild() {
        let mut p = Packet::dissect(vector(), ProtoId::Ipfix);
        let l = p.find_layer(ProtoId::Ipfix).unwrap();
        let n = p.raw_bytes().len();
        for f in crate::proto::active_fields(ProtoId::Ipfix, false, p.header(l))
            .filter(|f| f.kind == crate::field::FieldKind::Uint && f.bit_len <= 32)
            .map(|f| f.name)
            .collect::<Vec<_>>()
        {
            p.set_uint(l, f, 1);
        }
        assert_eq!(p.to_bytes().len(), n);
    }

    use crate::options::ItemValue;

    #[test]
    fn sets_read_at_the_width_their_own_length_claims() {
        let p = Packet::dissect(vector(), ProtoId::Ipfix);
        let l = p.find_layer(ProtoId::Ipfix).unwrap();
        let items = p.options(l).unwrap();
        assert_eq!(items.len(), 1);
        let ItemValue::Items(f) = &items[0].value else {
            panic!("not a record")
        };
        assert_eq!(f[0].value, ItemValue::Uint(2));
        assert_eq!(f[1].value, ItemValue::Uint(8));
        assert_eq!(f[2].value, ItemValue::Bytes(vec![1, 0, 0, 1]));
    }

    /// RFC 7011 §3.1: `length` covers the whole message, so a Set past it
    /// belongs to whatever follows rather than to this one.
    #[test]
    fn the_message_length_bounds_the_sets() {
        let mut data = vector();
        data.extend_from_slice(&[0x00, 0x02, 0x00, 0x04]);
        let p = Packet::dissect(data, ProtoId::Ipfix);
        let l = p.find_layer(ProtoId::Ipfix).unwrap();
        assert_eq!(p.options(l).unwrap().len(), 1);
    }
    // protogen:tests end
}
