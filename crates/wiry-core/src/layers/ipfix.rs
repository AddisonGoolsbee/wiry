/// RFC 7011 §3.1: Length covers the whole message.
fn content_len(hdr: &[u8]) -> usize {
    match hdr.get(2..4) {
        Some(b) => u16::from_be_bytes([b[0], b[1]]) as usize,
        None => 0,
    }
}

/// The Sets are inside the header, because that is the slice the walk is
/// handed, and `length` is what says where they stop.
fn header_len(hdr: &[u8]) -> usize {
    content_len(hdr).clamp(16, hdr.len().max(16))
}
