#[cfg(test)]
mod tests {
    #![allow(unused_imports)]
    use super::*;
    use crate::field::FieldValue;
    use crate::packet::Packet;

    // protogen:tests begin
    /// RFC 2710 §3 general query: maximum response delay 10000 ms, unspecified multicast address.
    fn vector() -> Vec<u8> {
        vec![
            0x82, 0x00, 0x00, 0x00, 0x27, 0x10, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
            0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        ]
    }

    #[test]
    fn dissects_the_rfc_vector() {
        let p = Packet::dissect(vector(), ProtoId::Icmpv6MlQuery);
        let l = p.find_layer(ProtoId::Icmpv6MlQuery).unwrap();
        assert_eq!(p.get(l, "type").unwrap(), FieldValue::Uint(130));
        assert_eq!(p.get(l, "code").unwrap(), FieldValue::Uint(0));
        assert_eq!(p.get(l, "cksum").unwrap(), FieldValue::Uint(0));
        assert_eq!(p.get(l, "mrd").unwrap(), FieldValue::Uint(10000));
        assert_eq!(p.get(l, "reserved").unwrap(), FieldValue::Uint(0));
        assert_eq!(p.raw_bytes(), &vector()[..]);
    }

    #[test]
    fn truncation_does_not_panic() {
        for n in 0..vector().len() {
            let p = Packet::dissect(vector()[..n].to_vec(), ProtoId::Icmpv6MlQuery);
            assert_eq!(p.raw_bytes(), &vector()[..n]);
        }
    }

    #[test]
    fn writes_survive_a_rebuild() {
        let mut p = Packet::dissect(vector(), ProtoId::Icmpv6MlQuery);
        let l = p.find_layer(ProtoId::Icmpv6MlQuery).unwrap();
        let n = p.raw_bytes().len();
        for f in crate::proto::active_fields(ProtoId::Icmpv6MlQuery, false, p.header(l))
            .filter(|f| f.kind == crate::field::FieldKind::Uint && f.bit_len <= 32)
            .map(|f| f.name)
            .collect::<Vec<_>>()
        {
            p.set_uint(l, f, 1);
        }
        assert_eq!(p.to_bytes().len(), n);
    }

    use crate::options::ItemValue;

    /// RFC 3810 §5.1: a version 2 query's source list is counted, and a version
    /// 1 query has none at all.
    #[test]
    fn a_version_two_query_reads_its_source_list() {
        let mut data = vector();
        data.extend_from_slice(&[0x02, 0x7d, 0x00, 0x01]);
        data.extend(std::iter::repeat_n(0u8, 16));
        data[43] = 9;
        let p = Packet::dissect(data, ProtoId::Icmpv6MlQuery);
        let l = p.find_layer(ProtoId::Icmpv6MlQuery).unwrap();
        assert_eq!(p.get(l, "QQIC").unwrap(), FieldValue::Uint(0x7d));
        let items = p.options(l).unwrap();
        assert_eq!(items.len(), 1);
        assert_eq!(items[0].name, "src");
        assert_eq!(items[0].value, ItemValue::Text("::9".into()));
    }

    #[test]
    fn a_version_one_query_carries_no_sources() {
        let p = Packet::dissect(vector(), ProtoId::Icmpv6MlQuery);
        let l = p.find_layer(ProtoId::Icmpv6MlQuery).unwrap();
        assert!(p.options(l).unwrap().is_empty());
        assert!(p.get(l, "QQIC").is_none());
    }
    // protogen:tests end
}
