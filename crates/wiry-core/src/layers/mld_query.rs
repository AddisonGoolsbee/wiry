// protogen:hand begin
/// RFC 3810 §5.1.20: a query of at least 28 octets is a version 2 query, and
/// length is the only thing that says so.
fn is_v2(hdr: &[u8]) -> bool {
    hdr.len() >= 28
}

fn header_len(hdr: &[u8]) -> usize {
    if !is_v2(hdr) {
        return 24;
    }
    (28 + crate::repeat::region_len(hdr, &GROUP)).min(hdr.len())
}
// protogen:hand end

pub static FIELDS: &[FieldDesc] = &[
    FieldDesc::uint("type", 0, 8, 130),
    FieldDesc::uint("code", 8, 8, 0),
    FieldDesc::uint("cksum", 16, 16, 0),
    FieldDesc::uint("mrd", 32, 16, 10000),
    FieldDesc::uint("reserved", 48, 16, 0),
    FieldDesc::ipv6("mladdr", 64),
    FieldDesc::uint("Resv", 192, 4, 0).when(is_v2),
    FieldDesc::uint("S", 196, 1, 0).when(is_v2),
    FieldDesc::uint("QRV", 197, 3, 0).when(is_v2),
    FieldDesc::uint("QQIC", 200, 8, 0).when(is_v2),
    FieldDesc::uint("sources_number", 208, 16, 0).when(is_v2),
    FieldDesc::var_bytes("sources", 224).when(is_v2),
];

pub static GROUP_FIELDS: &[FieldDesc] = &[FieldDesc::ipv6("src", 0)];

pub static GROUP: GroupDesc = GroupDesc::new(
    "sources",
    GROUP_FIELDS,
    ElemLen::Fixed(16),
    Extent::Count {
        bit_off: 208,
        bit_len: 16,
    },
    28,
)
.when(is_v2);

