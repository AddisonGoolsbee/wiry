//! RFC 2710 §3, Multicast Listener Query: ICMPv6 type 130, code 0, checksum, a
//! 16-bit Maximum Response Delay in milliseconds, a 16-bit reserved field and the
//! 128-bit multicast address. RFC 3810 §5.1 extends the same 24 octets with a
//! four-bit reserved field, an S bit, a three-bit QRV, a QQIC octet, a 16-bit
//! source count and that many 128-bit source addresses; a query of at least 28
//! octets is a version 2 query, which is why those fields are conditional on the
//! header length, and the source list is a count-driven repeating group
//! (`crates/wiry-core/src/repeat.rs`).
//!
//! scapy keeps the two versions as separate classes (`ICMPv6MLQuery` and
//! `ICMPv6MLQuery2`) and they are one layer here, as DEVIATIONS P12 records; the
//! version 2 field names are scapy's.
//!
//! Generated by dev/protogen from dev/protogen/specs/mld_query.toml. Field layouts
//! come from the RFC cited above; edit the spec, not this file.

