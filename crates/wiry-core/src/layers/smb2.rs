    #[test]
    fn dissects_the_rfc_vector() {
        let p = Packet::dissect(vector(), ProtoId::Smb2);
        let l = p.find_layer(ProtoId::Smb2).unwrap();
        assert_eq!(
            p.get(l, "ProtocolId").unwrap(),
            FieldValue::Uint(4266872130)
        );
        assert_eq!(p.get(l, "StructureSize").unwrap(), FieldValue::Uint(64));
        assert_eq!(p.get(l, "CreditCharge").unwrap(), FieldValue::Uint(0));
        assert_eq!(p.get(l, "Status").unwrap(), FieldValue::Uint(0));
        assert_eq!(p.get(l, "Command").unwrap(), FieldValue::Uint(0));
        assert_eq!(p.get(l, "CreditRequest").unwrap(), FieldValue::Uint(0));
        assert_eq!(p.get(l, "Flags").unwrap(), FieldValue::Uint(0));
        assert_eq!(p.get(l, "NextCommand").unwrap(), FieldValue::Uint(0));
        assert_eq!(p.get(l, "MessageId").unwrap(), FieldValue::Uint(0));
        assert_eq!(p.get(l, "Reserved").unwrap(), FieldValue::Uint(0));
        assert_eq!(p.get(l, "TreeId").unwrap(), FieldValue::Uint(0));
        assert_eq!(p.get(l, "SessionId").unwrap(), FieldValue::Uint(0));
        assert_eq!(p.raw_bytes(), &vector()[..]);
    }

    #[test]
    fn truncation_does_not_panic() {
        for n in 0..vector().len() {
            let p = Packet::dissect(vector()[..n].to_vec(), ProtoId::Smb2);
            assert_eq!(p.raw_bytes(), &vector()[..n]);
        }
    }

    #[test]
    fn writes_survive_a_rebuild() {
        let mut p = Packet::dissect(vector(), ProtoId::Smb2);
        let l = p.find_layer(ProtoId::Smb2).unwrap();
        let n = p.raw_bytes().len();
        for f in crate::proto::active_fields(ProtoId::Smb2, false, p.header(l))
            .filter(|f| f.kind == crate::field::FieldKind::Uint && f.bit_len <= 32)
            .map(|f| f.name)
            .collect::<Vec<_>>()
        {
            p.set_uint(l, f, 1);
        }
        assert_eq!(p.to_bytes().len(), n);
    }
