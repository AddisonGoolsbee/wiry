/// RFC 3416 §3: the PDU is a context-tagged choice; each name is scapy's
/// class for that alternative, which is what `pkt[SNMP].PDU` is an instance
/// of.
fn pdu_class(tag: u32) -> &'static str {
    match tag {
        0 => "SNMPget",
        1 => "SNMPnext",
        2 => "SNMPresponse",
        3 => "SNMPset",
        4 => "SNMPtrapv1",
        5 => "SNMPbulk",
        6 => "SNMPinform",
        7 => "SNMPtrapv2",
        _ => "PDU",
    }
}

/// The PDU's fields before its variable bindings, under scapy's names: RFC
/// 1157 §4.1.6 for a v1 trap, RFC 3416 §3 for GetBulk, and the request-id,
/// error-status, error-index triple for every other PDU.
fn pdu_fields(tag: u32) -> &'static [&'static str] {
    match tag {
        4 => &[
            "enterprise",
            "agent_addr",
            "generic_trap",
            "specific_trap",
            "time_stamp",
        ],
        5 => &["id", "non_repeaters", "max_repetitions"],
        _ => &["id", "error", "error_index"],
    }
}

/// Bindings reported per message. Every one `pkt[SNMP]` would hold is here
/// too, so the two agree; a binding is at least seven octets, which puts this
/// past anything a UDP datagram carries.
const MAX_VARBINDS: usize = 1 << 16;

/// RFC 3416 §3: a varbind's value is a value, or one of three context-tagged
/// NULLs saying why there is none. scapy names each by its field.
fn varbind_value(v: &ber::Tlv<'_>) -> ItemValue {
    match (v.class, v.tag) {
        (ber::CONTEXT, 0) => ItemValue::Text("noSuchObject".into()),
        (ber::CONTEXT, 1) => ItemValue::Text("noSuchInstance".into()),
        (ber::CONTEXT, 2) => ItemValue::Text("endOfMibView".into()),
        _ => ber::value(v),
    }
}

/// The message as scapy's object tree names it, flattened: `version`,
/// `community`, `PDU` (the alternative's class), the PDU's own fields, then
/// `varbindlist`, one item per binding named by its OID. The values are what
/// scapy's decoder gives each field's `.val`.
fn parse_options(hdr: &[u8]) -> Vec<Item> {
    let mut out = Vec::new();
    let Some(msg) = ber::read(hdr) else {
        return out;
    };
    let kids = ber::children(msg.value);
    if let Some(v) = kids.first() {
        out.push(Item::named("version", 0, ber::value(v)));
    }
    if let Some(c) = kids.get(1) {
        out.push(Item::named("community", 1, ber::value(c)));
    }
    let Some(pdu) = kids.get(2) else {
        return out;
    };
    out.push(Item::named(
        "PDU",
        pdu.tag,
        ItemValue::Text(pdu_class(pdu.tag).to_string()),
    ));
    let f = ber::children(pdu.value);
    let names = pdu_fields(pdu.tag);
    for (i, n) in names.iter().enumerate() {
        if let Some(x) = f.get(i) {
            out.push(Item::named(n, i as u32 + 3, ber::value(x)));
        }
    }
    let Some(vb) = f.get(names.len()).filter(|t| t.constructed) else {
        return out;
    };
    let mut binds = Vec::new();
    for b in ber::children_upto(vb.value, MAX_VARBINDS) {
        let kv = ber::children(b.value);
        if let (Some(o), Some(v)) = (kv.first(), kv.get(1)) {
            binds.push(Item {
                name: Cow::Owned(ber::oid(o.value)),
                code: 0,
                value: varbind_value(v),
            });
        }
    }
    out.push(Item::named(
        "varbindlist",
        names.len() as u32 + 3,
        ItemValue::Items(binds),
    ));
    out
}

