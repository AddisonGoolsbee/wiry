#[cfg(test)]
mod tests {
    #![allow(unused_imports)]
    use super::*;
    use crate::field::FieldValue;
    use crate::packet::Packet;

    // protogen:tests begin
    /// RFC 3954 §5.1 export header, hand-built: version 9, one FlowSet, uptime 1000 ms.
    fn vector() -> Vec<u8> {
        vec![
            0x00, 0x09, 0x00, 0x01, 0x00, 0x00, 0x03, 0xe8, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
            0x00, 0x01, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x08, 0x01, 0x00, 0x00, 0x01,
        ]
    }

    #[test]
    fn dissects_the_rfc_vector() {
        let p = Packet::dissect(vector(), ProtoId::NetflowV9);
        let l = p.find_layer(ProtoId::NetflowV9).unwrap();
        assert_eq!(p.get(l, "version").unwrap(), FieldValue::Uint(9));
        assert_eq!(p.get(l, "count").unwrap(), FieldValue::Uint(1));
        assert_eq!(p.get(l, "sysUptime").unwrap(), FieldValue::Uint(1000));
        assert_eq!(p.get(l, "unixSecs").unwrap(), FieldValue::Uint(0));
        assert_eq!(p.get(l, "sequenceNumber").unwrap(), FieldValue::Uint(1));
        assert_eq!(p.get(l, "SourceID").unwrap(), FieldValue::Uint(0));
        assert_eq!(p.raw_bytes(), &vector()[..]);
    }

    #[test]
    fn truncation_does_not_panic() {
        for n in 0..vector().len() {
            let p = Packet::dissect(vector()[..n].to_vec(), ProtoId::NetflowV9);
            assert_eq!(p.raw_bytes(), &vector()[..n]);
        }
    }

    #[test]
    fn writes_survive_a_rebuild() {
        let mut p = Packet::dissect(vector(), ProtoId::NetflowV9);
        let l = p.find_layer(ProtoId::NetflowV9).unwrap();
        let n = p.raw_bytes().len();
        for f in crate::proto::active_fields(ProtoId::NetflowV9, false, p.header(l))
            .filter(|f| f.kind == crate::field::FieldKind::Uint && f.bit_len <= 32)
            .map(|f| f.name)
            .collect::<Vec<_>>()
        {
            p.set_uint(l, f, 1);
        }
        assert_eq!(p.to_bytes().len(), n);
    }

    use crate::options::ItemValue;

    #[test]
    fn flowsets_read_at_the_width_their_own_length_claims() {
        let mut data = vector();
        data.extend_from_slice(&[0x01, 0x00, 0x00, 0x04]);
        let p = Packet::dissect(data, ProtoId::NetflowV9);
        let l = p.find_layer(ProtoId::NetflowV9).unwrap();
        let items = p.options(l).unwrap();
        assert_eq!(items.len(), 2);
        let ItemValue::Items(f) = &items[0].value else {
            panic!("not a record")
        };
        assert_eq!(f[0].value, ItemValue::Uint(0));
        assert_eq!(f[1].value, ItemValue::Uint(8));
        assert_eq!(f[2].value, ItemValue::Bytes(vec![1, 0, 0, 1]));
    }

    /// A length below the four octets a FlowSet header needs cannot advance the
    /// walk by less than one header, or the records would overlap.
    #[test]
    fn a_length_below_the_flowset_header_does_not_overlap() {
        let mut data = vector()[..20].to_vec();
        data.extend_from_slice(&[0x01, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x04]);
        let p = Packet::dissect(data, ProtoId::NetflowV9);
        let l = p.find_layer(ProtoId::NetflowV9).unwrap();
        assert_eq!(p.options(l).unwrap().len(), 2);
    }
    // protogen:tests end
}
