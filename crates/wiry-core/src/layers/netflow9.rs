//! RFC 3954 §5.1: a 16-bit version (9), a 16-bit count of FlowSets, the 32-bit
//! system uptime in milliseconds, the 32-bit UNIX export time, a 32-bit sequence
//! number and a 32-bit source id. §5.2 and §5.3 give every FlowSet the same two
//! leading fields — a 16-bit FlowSet id (0 template, 1 options, 256 and up data)
//! and a 16-bit length covering both of them and the records — so the FlowSets are
//! a repeating group whose element width is its own length field
//! (`crates/wiry-core/src/repeat.rs`), running to the end of the datagram.
//!
//! The FlowSet *contents* are not decoded: a data FlowSet needs the template the
//! exporter sent in an earlier datagram, which is per-session state this dissector
//! does not keep (DEVIATIONS P6). The header's `count` is not used as the element
//! count either, because §5.1 defines it as the number of records across all
//! FlowSets rather than the number of FlowSets.
//!
//! Generated by dev/protogen from dev/protogen/specs/netflow9.toml. Field layouts
//! come from the RFC cited above; edit the spec, not this file.

