fn record_len(hdr: &[u8]) -> usize {
    match hdr.get(3..5) {
        Some(b) => 5 + u16::from_be_bytes([b[0], b[1]]) as usize,
        None => 5,
    }
}

/// The whole record is the header, so the handshake inside it is in reach of
/// the parser; a second record in the same segment stays payload.
fn header_len(hdr: &[u8]) -> usize {
    record_len(hdr).min(hdr.len()).max(5)
}

/// RFC 6066 §3: a 16-bit list length, a one-octet name type and a 16-bit host
/// name length.
fn server_name(v: &[u8]) -> Option<String> {
    let n = u16::from_be_bytes([*v.get(3)?, *v.get(4)?]) as usize;
    Some(String::from_utf8_lossy(v.get(5..5 + n)?).into_owned())
}

