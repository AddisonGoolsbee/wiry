/// RFC 8446 §4.1.2 and §4.1.3: both hellos start with a legacy version and a
/// 32-octet random, then differ only in how the cipher suite and compression
/// fields are sized.
fn hello_extensions(body: &[u8], handshake: u8) -> Option<&[u8]> {
    let mut i = 4 + 2 + 32;
    i += 1 + *body.get(i)? as usize;
    if handshake == 1 {
        let b = body.get(i..i + 2)?;
        i += 2 + u16::from_be_bytes([b[0], b[1]]) as usize;
        i += 1 + *body.get(i)? as usize;
    } else {
        i += 3;
    }
    let b = body.get(i..i + 2)?;
    let n = u16::from_be_bytes([b[0], b[1]]) as usize;
    body.get(i + 2..i + 2 + n)
}

