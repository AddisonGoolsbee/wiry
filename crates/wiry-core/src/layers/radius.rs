/// RFC 2865 §3: Length covers the whole packet and is at least 20.
fn message_len(hdr: &[u8]) -> usize {
    match hdr.get(2..4) {
        Some(b) => (u16::from_be_bytes([b[0], b[1]]) as usize).max(20),
        None => 20,
    }
}

fn header_len(hdr: &[u8]) -> usize {
    message_len(hdr)
}

fn content_len(hdr: &[u8]) -> usize {
    message_len(hdr)
}

