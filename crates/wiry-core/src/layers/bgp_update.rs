use crate::options::{Item, ItemValue};

/// Every walk here is over an attacker-controlled length, so each is bounded
/// and each returns what it managed.
const MAX_ITEMS: usize = 512;

fn be16(b: &[u8], at: usize) -> usize {
    match b.get(at..at + 2) {
        Some(w) => u16::from_be_bytes([w[0], w[1]]) as usize,
        None => 0,
    }
}

/// RFC 4271 §5 path attribute type codes, and RFC 1997, 4456, 4760, 4360,
/// 6793, 7311 and 8092 for the ones registered since.
fn attr_name(code: u8) -> Option<&'static str> {
    Some(match code {
        1 => "ORIGIN",
        2 => "AS_PATH",
        3 => "NEXT_HOP",
        4 => "MULTI_EXIT_DISC",
        5 => "LOCAL_PREF",
        6 => "ATOMIC_AGGREGATE",
        7 => "AGGREGATOR",
        8 => "COMMUNITY",
        9 => "ORIGINATOR_ID",
        10 => "CLUSTER_LIST",
        14 => "MP_REACH_NLRI",
        15 => "MP_UNREACH_NLRI",
        16 => "EXTENDED COMMUNITIES",
        17 => "AS4_PATH",
        18 => "AS4_AGGREGATOR",
        26 => "AIGP",
        32 => "LARGE_COMMUNITY",
        _ => return None,
    })
}

/// RFC 4271 §4.3: a prefix is a length in bits and only the octets that hold
/// it. Rendered the way an address leaves the engine everywhere else.
fn prefixes(region: &[u8], name: &'static str, out: &mut Vec<Item>) {
    let mut i = 0usize;
    while i < region.len() && out.len() < MAX_ITEMS {
        let bits = region[i] as usize;
        if bits > 32 {
            break;
        }
        let octets = bits.div_ceil(8);
        let Some(p) = region.get(i + 1..i + 1 + octets) else {
            break;
        };
        let mut a = [0u8; 4];
        a[..octets].copy_from_slice(p);
        out.push(Item::named(
            name,
            bits as u32,
            ItemValue::Text(format!("{}.{}.{}.{}/{}", a[0], a[1], a[2], a[3], bits)),
        ));
        i += 1 + octets;
    }
}

/// §4.3: the length is two octets rather than one when the Extended Length bit
/// is set, so reading it with the wrong width mis-decodes every attribute
/// after the first rather than failing.
fn attributes(region: &[u8], out: &mut Vec<Item>) {
    let mut i = 0usize;
    while i + 3 <= region.len() && out.len() < MAX_ITEMS {
        let flags = region[i];
        let code = region[i + 1];
        let wide = flags & 0x10 != 0;
        let (hdr, len) = if wide {
            (4, be16(region, i + 2))
        } else {
            (3, region[i + 2] as usize)
        };
        let Some(v) = region.get(i + hdr..i + hdr + len) else {
            break;
        };
        out.push(match attr_name(code) {
            Some(n) => Item::bytes(n, code as u32, v),
            None => Item::unknown(code as u32, v),
        });
        i += hdr + len;
    }
}

fn parse_options(hdr: &[u8]) -> Vec<Item> {
    let mut out = Vec::new();
    let wlen = be16(hdr, 0);
    let Some(withdrawn) = hdr.get(2..2 + wlen) else {
        return out;
    };
    prefixes(withdrawn, "withdrawn", &mut out);
    let at = 2 + wlen;
    let alen = be16(hdr, at);
    let Some(attrs) = hdr.get(at + 2..at + 2 + alen) else {
        return out;
    };
    attributes(attrs, &mut out);
    prefixes(hdr.get(at + 2 + alen..).unwrap_or(&[]), "nlri", &mut out);
    out
}
