#[cfg(test)]
mod tests {
    #![allow(unused_imports)]
    use super::*;
    use crate::field::FieldValue;
    use crate::packet::Packet;

    // protogen:tests begin
    /// RFC 4271 §4.3 UPDATE, hand-built: no withdrawn routes, ORIGIN=IGP and NEXT_HOP=10.0.0.1, advertising 192.168.1.0/24.
    fn vector() -> Vec<u8> {
        vec![
            0x00, 0x00, 0x00, 0x0b, 0x40, 0x01, 0x01, 0x00, 0x40, 0x03, 0x04, 0x0a, 0x00, 0x00,
            0x01, 0x18, 0xc0, 0xa8, 0x01,
        ]
    }

    #[test]
    fn dissects_the_rfc_vector() {
        let p = Packet::dissect(vector(), ProtoId::BgpUpdate);
        let l = p.find_layer(ProtoId::BgpUpdate).unwrap();
        assert_eq!(
            p.get(l, "withdrawn_routes_len").unwrap(),
            FieldValue::Uint(0)
        );
        assert_eq!(p.raw_bytes(), &vector()[..]);
    }

    #[test]
    fn truncation_does_not_panic() {
        for n in 0..vector().len() {
            let p = Packet::dissect(vector()[..n].to_vec(), ProtoId::BgpUpdate);
            assert_eq!(p.raw_bytes(), &vector()[..n]);
        }
    }

    #[test]
    fn writes_survive_a_rebuild() {
        let mut p = Packet::dissect(vector(), ProtoId::BgpUpdate);
        let l = p.find_layer(ProtoId::BgpUpdate).unwrap();
        let n = p.raw_bytes().len();
        for f in crate::proto::active_fields(ProtoId::BgpUpdate, false, p.header(l))
            .filter(|f| f.kind == crate::field::FieldKind::Uint && f.bit_len <= 32)
            .map(|f| f.name)
            .collect::<Vec<_>>()
        {
            p.set_uint(l, f, 1);
        }
        assert_eq!(p.to_bytes().len(), n);
    }

    #[test]
    fn path_attributes_and_nlri_read_under_one_list() {
        let p = Packet::dissect(vector(), ProtoId::BgpUpdate);
        let l = p.find_layer(ProtoId::BgpUpdate).unwrap();
        let items = p.options(l).unwrap();
        assert_eq!(
            items.iter().map(|i| i.name.as_ref()).collect::<Vec<_>>(),
            vec!["ORIGIN", "NEXT_HOP", "nlri"]
        );
        assert_eq!(items[0].value, ItemValue::Bytes(vec![0]));
        assert_eq!(items[1].value, ItemValue::Bytes(vec![10, 0, 0, 1]));
        assert_eq!(items[2].value, ItemValue::Text("192.168.1.0/24".into()));
    }

    /// RFC 4271 §4.3: the Extended Length bit widens the length octet, and
    /// reading it at the wrong width mis-decodes every attribute after it.
    #[test]
    fn an_extended_length_attribute_is_read_at_two_octets() {
        let mut data = vec![0u8, 0, 0, 9, 0x50, 0x0e, 0x00, 0x05, 1, 2, 3, 4, 5];
        data.extend_from_slice(&[0x08, 0x0a]);
        let p = Packet::dissect(data, ProtoId::BgpUpdate);
        let l = p.find_layer(ProtoId::BgpUpdate).unwrap();
        let items = p.options(l).unwrap();
        assert_eq!(items[0].name, "MP_REACH_NLRI");
        assert_eq!(items[0].value, ItemValue::Bytes(vec![1, 2, 3, 4, 5]));
        assert_eq!(items[1].value, ItemValue::Text("10.0.0.0/8".into()));
    }

    #[test]
    fn withdrawn_routes_are_named_apart_from_advertised_ones() {
        let data = vec![0u8, 3, 0x10, 0x0a, 0x00, 0x00, 0x00];
        let p = Packet::dissect(data, ProtoId::BgpUpdate);
        let l = p.find_layer(ProtoId::BgpUpdate).unwrap();
        let items = p.options(l).unwrap();
        assert_eq!(items.len(), 1);
        assert_eq!(items[0].name, "withdrawn");
        assert_eq!(items[0].value, ItemValue::Text("10.0.0.0/16".into()));
    }

    #[test]
    fn a_prefix_length_no_address_can_hold_stops_the_walk() {
        let data = vec![0u8, 0, 0, 0, 0xff, 1, 2, 3, 4];
        let p = Packet::dissect(data, ProtoId::BgpUpdate);
        let l = p.find_layer(ProtoId::BgpUpdate).unwrap();
        assert!(p.options(l).unwrap().is_empty());
    }
    // protogen:tests end
}
