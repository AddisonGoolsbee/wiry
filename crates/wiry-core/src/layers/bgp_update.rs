//! RFC 4271 §4.3, UPDATE message: a 16-bit count of withdrawn-route octets, that
//! many withdrawn routes, a 16-bit count of path-attribute octets, that many path
//! attributes, and then the Network Layer Reachability Information to the end of
//! the message. §4.3 encodes a route as a one-octet prefix length in *bits*
//! followed by the smallest number of octets that holds it, and a path attribute
//! as an attribute-flags octet, a type octet and a length that is one octet, or
//! two when the flags' Extended Length bit (0x10) is set.
//!
//! Three variable regions in sequence, two of them at offsets no earlier field
//! fixes, is outside the flat table and outside the repeating-group construct
//! alike, so the whole body past `withdrawn_routes_len` is one variable field and
//! the walk over it is hand-written. It answers one list under `body`, whose item
//! names say which of the three regions each came from: `withdrawn` for a
//! withdrawn prefix, the RFC 4271 §5 attribute name (or its code) for a path
//! attribute, and `nlri` for an advertised prefix. Path attribute *values* are
//! kept as octets: their layout varies by type code — DEVIATIONS E1.
//!
//! Generated by dev/protogen from dev/protogen/specs/bgp_update.toml. Field layouts
//! come from the RFC cited above; edit the spec, not this file.

