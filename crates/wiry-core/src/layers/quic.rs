/// A short header's connection id length is known only to the endpoints, so
/// only the first octet is claimed as header.
fn header_len(hdr: &[u8]) -> usize {
    if !is_long(hdr) {
        return 1;
    }
    let (_, sl_at, sl) = cid_lens(hdr);
    (sl_at + 1 + sl).min(hdr.len()).max(1)
}

