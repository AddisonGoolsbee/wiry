#[cfg(test)]
mod tests {
    #![allow(unused_imports)]
    use super::*;
    use crate::field::FieldValue;
    use crate::packet::Packet;

    // protogen:tests begin
    /// RFC 4271 §4.2 OPEN, hand-built: version 4, AS 65001, hold time 180, id 10.0.0.1, one two-octet capability parameter.
    fn vector() -> Vec<u8> {
        vec![
            0x04, 0xfd, 0xe9, 0x00, 0xb4, 0x0a, 0x00, 0x00, 0x01, 0x04, 0x02, 0x02, 0x01, 0x04,
        ]
    }

    #[test]
    fn dissects_the_rfc_vector() {
        let p = Packet::dissect(vector(), ProtoId::BgpOpen);
        let l = p.find_layer(ProtoId::BgpOpen).unwrap();
        assert_eq!(p.get(l, "version").unwrap(), FieldValue::Uint(4));
        assert_eq!(p.get(l, "my_as").unwrap(), FieldValue::Uint(65001));
        assert_eq!(p.get(l, "hold_time").unwrap(), FieldValue::Uint(180));
        assert_eq!(p.get(l, "opt_param_len").unwrap(), FieldValue::Uint(4));
        assert_eq!(p.raw_bytes(), &vector()[..]);
    }

    #[test]
    fn truncation_does_not_panic() {
        for n in 0..vector().len() {
            let p = Packet::dissect(vector()[..n].to_vec(), ProtoId::BgpOpen);
            assert_eq!(p.raw_bytes(), &vector()[..n]);
        }
    }

    #[test]
    fn writes_survive_a_rebuild() {
        let mut p = Packet::dissect(vector(), ProtoId::BgpOpen);
        let l = p.find_layer(ProtoId::BgpOpen).unwrap();
        let n = p.raw_bytes().len();
        for f in crate::proto::active_fields(ProtoId::BgpOpen, false, p.header(l))
            .filter(|f| f.kind == crate::field::FieldKind::Uint && f.bit_len <= 32)
            .map(|f| f.name)
            .collect::<Vec<_>>()
        {
            p.set_uint(l, f, 1);
        }
        assert_eq!(p.to_bytes().len(), n);
    }

    use crate::options::ItemValue;

    #[test]
    fn optional_parameters_read_as_a_group() {
        let p = Packet::dissect(vector(), ProtoId::BgpOpen);
        let l = p.find_layer(ProtoId::BgpOpen).unwrap();
        let items = p.options(l).unwrap();
        assert_eq!(items.len(), 1);
        assert_eq!(items[0].name, "BGPOptParam");
        let ItemValue::Items(f) = &items[0].value else {
            panic!("not a record")
        };
        assert_eq!(f[0].value, ItemValue::Uint(2));
        assert_eq!(f[1].value, ItemValue::Uint(2));
        assert_eq!(f[2].value, ItemValue::Bytes(vec![1, 4]));
    }

    /// `opt_param_len` bounds the region, so octets past it are not parameters
    /// however well formed they look.
    #[test]
    fn octets_past_the_declared_length_are_not_parameters() {
        let mut data = vector();
        data[9] = 0;
        let p = Packet::dissect(data, ProtoId::BgpOpen);
        let l = p.find_layer(ProtoId::BgpOpen).unwrap();
        assert!(p.options(l).unwrap().is_empty());
    }

    #[test]
    fn parameters_encode_back_to_the_bytes_they_came_from() {
        let p = Packet::dissect(vector(), ProtoId::BgpOpen);
        let l = p.find_layer(ProtoId::BgpOpen).unwrap();
        let items = p.options(l).unwrap();
        assert_eq!(
            crate::repeat::encode(&GROUP, &items).unwrap(),
            vector()[10..]
        );
    }
    // protogen:tests end
}
