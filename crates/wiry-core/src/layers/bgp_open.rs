//! RFC 4271 §4.2, OPEN message: a one-octet version (4), the 16-bit autonomous
//! system number of the sender, a 16-bit hold time in seconds, the four-octet BGP
//! identifier, a one-octet length of the optional parameters, and then that many
//! octets of them. §4.2 gives an optional parameter a one-octet type and a
//! one-octet length that counts only the value, so the parameters are a
//! length-driven repeating group (`crates/wiry-core/src/repeat.rs`) whose element
//! is two octets plus its own length.
//!
//! The parameter *value* is kept as octets rather than decoded: RFC 5492 §4 makes
//! a type 2 value a list of capabilities and RFC 4271 makes a type 1 value
//! authentication data, so the layout varies by the type octet, which a flat
//! record table cannot express — DEVIATIONS E1.
//!
//! Generated by dev/protogen from dev/protogen/specs/bgp_open.toml. Field layouts
//! come from the RFC cited above; edit the spec, not this file.

