#[cfg(test)]
mod tests {
    #![allow(unused_imports)]
    use super::*;
    use crate::field::FieldValue;
    use crate::packet::Packet;

    // protogen:tests begin
    /// RFC 2328 §A.3.6 acknowledgement, hand-built: one LSA header, type 1, id 10.0.0.1.
    fn vector() -> Vec<u8> {
        vec![
            0x00, 0x01, 0x02, 0x01, 0x0a, 0x00, 0x00, 0x01, 0x0a, 0x00, 0x00, 0x01, 0x80, 0x00,
            0x00, 0x01, 0x00, 0x00, 0x00, 0x24,
        ]
    }

    #[test]
    fn dissects_the_rfc_vector() {
        let p = Packet::dissect(vector(), ProtoId::OspfLsAck);
        assert!(p.find_layer(ProtoId::OspfLsAck).is_some());

        assert_eq!(p.raw_bytes(), &vector()[..]);
    }

    #[test]
    fn truncation_does_not_panic() {
        for n in 0..vector().len() {
            let p = Packet::dissect(vector()[..n].to_vec(), ProtoId::OspfLsAck);
            assert_eq!(p.raw_bytes(), &vector()[..n]);
        }
    }

    #[test]
    fn writes_survive_a_rebuild() {
        let mut p = Packet::dissect(vector(), ProtoId::OspfLsAck);
        let l = p.find_layer(ProtoId::OspfLsAck).unwrap();
        let n = p.raw_bytes().len();
        for f in crate::proto::active_fields(ProtoId::OspfLsAck, false, p.header(l))
            .filter(|f| f.kind == crate::field::FieldKind::Uint && f.bit_len <= 32)
            .map(|f| f.name)
            .collect::<Vec<_>>()
        {
            p.set_uint(l, f, 1);
        }
        assert_eq!(p.to_bytes().len(), n);
    }

    use crate::options::ItemValue;

    fn fields(it: &crate::options::Item) -> Vec<(&str, ItemValue)> {
        let ItemValue::Items(v) = &it.value else {
            panic!("not a record")
        };
        v.iter()
            .map(|f| (f.name.as_ref(), f.value.clone()))
            .collect()
    }

    #[test]
    fn lsa_headers_read_as_a_group() {
        let mut data = vector();
        data.extend(vector());
        let p = Packet::dissect(data, ProtoId::OspfLsAck);
        let l = p.find_layer(ProtoId::OspfLsAck).unwrap();
        let items = p.options(l).unwrap();
        assert_eq!(items.len(), 2);
        assert_eq!(items[0].name, "OSPF_LSA_Hdr");
        let f = fields(&items[0]);
        assert_eq!(f[0], ("age", ItemValue::Uint(1)));
        assert_eq!(f[2], ("type", ItemValue::Uint(1)));
        assert_eq!(f[3], ("id", ItemValue::Text("10.0.0.1".into())));
        assert_eq!(f[7], ("len", ItemValue::Uint(0x24)));
    }

    #[test]
    fn lsa_headers_encode_back_to_the_bytes_they_came_from() {
        let p = Packet::dissect(vector(), ProtoId::OspfLsAck);
        let l = p.find_layer(ProtoId::OspfLsAck).unwrap();
        let items = p.options(l).unwrap();
        assert_eq!(crate::repeat::encode(&GROUP, &items).unwrap(), vector());
    }
    // protogen:tests end
}
