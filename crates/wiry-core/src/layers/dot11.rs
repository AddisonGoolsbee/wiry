#[cfg(test)]
mod tests {
    #![allow(unused_imports)]
    use super::*;
    use crate::field::FieldValue;
    use crate::packet::Packet;

    // protogen:tests begin
    /// IEEE 802.11-2020 §9.3.3.3 beacon, hand-built: type 0 subtype 8, broadcast addr1, BSSID 00:11:22:33:44:55.
    fn vector() -> Vec<u8> {
        vec![
            0x80, 0x00, 0x00, 0x00, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0x00, 0x11, 0x22, 0x33,
            0x44, 0x55, 0x00, 0x11, 0x22, 0x33, 0x44, 0x55, 0x00, 0x00,
        ]
    }

    #[test]
    fn dissects_the_rfc_vector() {
        let p = Packet::dissect(vector(), ProtoId::Dot11);
        let l = p.find_layer(ProtoId::Dot11).unwrap();
        assert_eq!(p.get(l, "subtype").unwrap(), FieldValue::Uint(8));
        assert_eq!(p.get(l, "type").unwrap(), FieldValue::Uint(0));
        assert_eq!(p.get(l, "proto").unwrap(), FieldValue::Uint(0));
        assert_eq!(p.get(l, "ID").unwrap(), FieldValue::Uint(0));
        assert_eq!(p.get(l, "SC").unwrap(), FieldValue::Uint(0));
        assert_eq!(p.raw_bytes(), &vector()[..]);
    }

    #[test]
    fn truncation_does_not_panic() {
        for n in 0..vector().len() {
            let p = Packet::dissect(vector()[..n].to_vec(), ProtoId::Dot11);
            assert_eq!(p.raw_bytes(), &vector()[..n]);
        }
    }

    #[test]
    fn writes_survive_a_rebuild() {
        let mut p = Packet::dissect(vector(), ProtoId::Dot11);
        let l = p.find_layer(ProtoId::Dot11).unwrap();
        let n = p.raw_bytes().len();
        for f in crate::proto::active_fields(ProtoId::Dot11, false, p.header(l))
            .filter(|f| f.kind == crate::field::FieldKind::Uint && f.bit_len <= 32)
            .map(|f| f.name)
            .collect::<Vec<_>>()
        {
            p.set_uint(l, f, 1);
        }
        assert_eq!(p.to_bytes().len(), n);
    }
    // protogen:tests end
}
