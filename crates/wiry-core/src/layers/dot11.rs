/// scapy's `Dot11.guess_payload_class`: QoS data first, then a protected
/// body, then the bindings.
fn next(hdr: &[u8]) -> Next {
    let (t, s) = (frame_type(hdr), subtype(hdr));
    if t == 2 && s >= 8 && s != 13 {
        return Next::Proto(ProtoId::Dot11QoS);
    }
    if protected(hdr) {
        return Next::Proto(ProtoId::Dot11Encrypted);
    }
    if let Some(&(_, _, p)) = BOUND.iter().find(|&&(bt, bs, _)| (bt, bs) == (t, s)) {
        return Next::Proto(p);
    }
    match (t, s) {
        // A Null Data frame (subtype bit 2) carries nothing to dissect.
        (2, s) if s & 0x04 == 0 => Next::Proto(ProtoId::Llc),
        _ => Next::Raw,
    }
}

fn bind_next(hdr: &mut [u8], p: ProtoId) {
    let (t, s) = match BOUND.iter().find(|&&(_, _, b)| b == p) {
        Some(&(t, s, _)) => (t, s),
        None if p == ProtoId::Llc => (2, subtype(hdr)),
        None => return,
    };
    if let Some(b) = hdr.first_mut() {
        *b = (*b & 0x03) | (t << 2) | (s << 4);
    }
}

/// IEEE 802.11-2020 §9.4.2.1: a one-octet element id and a one-octet length.
const ELEMENTS: TlvFmt = TlvFmt::new(8, 8);

fn element_name(t: u32) -> Option<&'static str> {
    Some(match t {
        0 => "SSID",
        1 => "Rates",
        3 => "DSset",
        5 => "TIM",
        7 => "Country",
        42 => "ERPinfo",
        45 => "HTCapabilities",
        48 => "RSNinfo",
        50 => "ESRates",
        61 => "HTinfo",
        221 => "Vendor",
        _ => return None,
    })
}

/// `at` is where the fixed part of a management body ends (IEEE 802.11-2020
/// §9.3.3), which differs per subtype.
pub fn info_elements(hdr: &[u8], at: usize) -> Vec<Item> {
    let Some(region) = hdr.get(at..) else {
        return Vec::new();
    };
    tlv::walk(region, &ELEMENTS)
        .into_iter()
        .map(|r| match (element_name(r.tag), r.tag) {
            (Some(n), 0 | 7) => tlv::text_item(n, r.tag, r.value),
            (Some(n), _) => Item::bytes(n, r.tag, r.value),
            (None, _) => Item::unknown(r.tag, r.value),
        })
        .collect()
}
