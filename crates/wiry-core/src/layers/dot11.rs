//! IEEE Std 802.11-2020 §9.2.4: the MAC header is a two-octet Frame Control field
//! (§9.2.4.1: protocol version, type, subtype, then the eight To DS / From DS /
//! More Fragments / Retry / Power Management / More Data / Protected / +HTC bits),
//! a two-octet Duration/ID, three addresses, a Sequence Control word, and a fourth
//! address only when both To DS and From DS are set (§9.2.4.5). The two octets of
//! QoS Control a QoS Data frame carries (§9.2.4.5.1) are the Dot11QoS layer that
//! follows, as in scapy, and a frame with the Protected bit set continues as
//! Dot11Encrypted. Control frames carry no third address or Sequence Control and
//! only some carry a second address (§9.3.1), and the S1G Beacon of §9.3.4.3 has
//! the first address alone. Frame Control and Duration are little-endian on the
//! wire (§9.2.2).
//!
//! Generated by dev/protogen from dev/protogen/specs/dot11.toml. Field layouts
//! come from the sources cited above; edit the spec, not this file.

