fn fc(hdr: &[u8]) -> u8 {
    hdr.first().copied().unwrap_or(0)
}

fn frame_type(hdr: &[u8]) -> u8 {
    (fc(hdr) >> 2) & 0x03
}

fn subtype(hdr: &[u8]) -> u8 {
    fc(hdr) >> 4
}

/// scapy's conditions on `Dot11.fields_desc`, which agree with §9.3: the
/// control-wrapper frame's `cfe` layout is not modelled.
fn has_addr2(hdr: &[u8]) -> bool {
    !matches!(frame_type(hdr), 1 | 3) || matches!(subtype(hdr), 4..=6 | 8..=11 | 14 | 15)
}

fn has_addr3(hdr: &[u8]) -> bool {
    matches!(frame_type(hdr), 0 | 2)
}

fn has_sc(hdr: &[u8]) -> bool {
    !matches!(frame_type(hdr), 1 | 3)
}

fn has_addr4(hdr: &[u8]) -> bool {
    frame_type(hdr) == 2 && hdr.get(1).is_some_and(|f| f & 0x03 == 0x03)
}

fn header_len(hdr: &[u8]) -> usize {
    10 + 6 * usize::from(has_addr2(hdr))
        + 6 * usize::from(has_addr3(hdr))
        + 2 * usize::from(has_sc(hdr))
        + 6 * usize::from(has_addr4(hdr))
}

fn protected(hdr: &[u8]) -> bool {
    hdr.get(1).is_some_and(|f| f & 0x40 != 0)
}

