#[cfg(test)]
mod tests {
    #![allow(unused_imports)]
    use super::*;
    use crate::field::FieldValue;
    use crate::packet::Packet;

    // protogen:tests begin
    /// RFC 2328 §A.3.2 hello, hand-built: mask 255.255.255.0, interval 10 s, dead interval 40 s, one neighbour 10.0.0.2.
    fn vector() -> Vec<u8> {
        vec![
            0xff, 0xff, 0xff, 0x00, 0x00, 0x0a, 0x02, 0x01, 0x00, 0x00, 0x00, 0x28, 0x0a, 0x00,
            0x00, 0x01, 0x00, 0x00, 0x00, 0x00, 0x0a, 0x00, 0x00, 0x02,
        ]
    }

    #[test]
    fn dissects_the_rfc_vector() {
        let p = Packet::dissect(vector(), ProtoId::OspfHello);
        let l = p.find_layer(ProtoId::OspfHello).unwrap();
        assert_eq!(p.get(l, "hellointerval").unwrap(), FieldValue::Uint(10));
        assert_eq!(p.get(l, "prio").unwrap(), FieldValue::Uint(1));
        assert_eq!(p.get(l, "deadinterval").unwrap(), FieldValue::Uint(40));
        assert_eq!(p.raw_bytes(), &vector()[..]);
    }

    #[test]
    fn truncation_does_not_panic() {
        for n in 0..vector().len() {
            let p = Packet::dissect(vector()[..n].to_vec(), ProtoId::OspfHello);
            assert_eq!(p.raw_bytes(), &vector()[..n]);
        }
    }

    #[test]
    fn writes_survive_a_rebuild() {
        let mut p = Packet::dissect(vector(), ProtoId::OspfHello);
        let l = p.find_layer(ProtoId::OspfHello).unwrap();
        let n = p.raw_bytes().len();
        for f in crate::proto::active_fields(ProtoId::OspfHello, false, p.header(l))
            .filter(|f| f.kind == crate::field::FieldKind::Uint && f.bit_len <= 32)
            .map(|f| f.name)
            .collect::<Vec<_>>()
        {
            p.set_uint(l, f, 1);
        }
        assert_eq!(p.to_bytes().len(), n);
    }

    use crate::options::{Item, ItemValue};

    #[test]
    fn neighbours_read_as_a_scalar_list() {
        let mut data = vector();
        data.extend_from_slice(&[10, 0, 0, 3]);
        let p = Packet::dissect(data, ProtoId::OspfHello);
        let l = p.find_layer(ProtoId::OspfHello).unwrap();
        let items = p.options(l).unwrap();
        assert_eq!(items.len(), 2);
        assert_eq!(items[0].name, "neighbor");
        assert_eq!(items[0].value, ItemValue::Text("10.0.0.2".into()));
        assert_eq!(items[1].value, ItemValue::Text("10.0.0.3".into()));
    }

    /// A trailing octet that cannot hold a router id is dropped rather than
    /// read past: a hello arrives snaplen-clipped like anything else.
    #[test]
    fn a_partial_trailing_neighbour_is_dropped() {
        let mut data = vector();
        data.extend_from_slice(&[10, 0]);
        let p = Packet::dissect(data, ProtoId::OspfHello);
        let l = p.find_layer(ProtoId::OspfHello).unwrap();
        assert_eq!(p.options(l).unwrap().len(), 1);
    }

    #[test]
    fn neighbours_encode_back_to_the_bytes_they_came_from() {
        let p = Packet::dissect(vector(), ProtoId::OspfHello);
        let l = p.find_layer(ProtoId::OspfHello).unwrap();
        let items = p.options(l).unwrap();
        assert_eq!(
            crate::repeat::encode(&GROUP, &items).unwrap(),
            vector()[20..]
        );
    }

    #[test]
    fn a_neighbour_a_caller_names_encodes_to_its_octets() {
        let it = crate::repeat::item(
            &GROUP,
            "neighbors",
            &crate::options::OptArg::Text("10.0.0.7".into()),
        )
        .unwrap();
        assert_eq!(
            crate::repeat::encode(&GROUP, std::slice::from_ref(&it)).unwrap(),
            vec![10, 0, 0, 7]
        );
        let _: &Item = &it;
    }
    // protogen:tests end
}
