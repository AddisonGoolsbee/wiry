//! RFC 2328 §A.3.2, Hello packet: a 32-bit network mask, a 16-bit HelloInterval in
//! seconds, the one-octet Options field of §A.2, a one-octet router priority, a
//! 32-bit RouterDeadInterval, the designated router and the backup designated
//! router, and then the router id of every neighbour heard from — a four-octet
//! list running to the end of the packet the header's `len` declares, which is a
//! repeating group (`crates/wiry-core/src/repeat.rs`).
//!
//! RFC 5613 §2.2 appends a Link-Local Signalling block after the packet `len` when
//! the Options L bit is set. That block is outside `len`, so it arrives as trailing
//! bytes rather than as a layer; see DEVIATIONS P3.
//!
//! Generated by dev/protogen from dev/protogen/specs/ospf_hello.toml. Field layouts
//! come from the RFC cited above; edit the spec, not this file.

