/// RFC 9260 §3.2: a type octet, a flags octet, a 16-bit length counting all
/// three, and a value padded out to a four-octet boundary.
const CHUNKS: TlvFmt = TlvFmt::new(8, 16).with_mid(8).covering_header().aligned(4);

/// §3.2.1 gives a chunk parameter the same shape at sixteen bits, and §3.3.10
/// gives an error cause the same shape again.
const PARAMS: TlvFmt = TlvFmt::new(16, 16).covering_header().aligned(4);

