fn items(region: &[u8], namer: fn(u32) -> Option<&'static str>) -> Vec<Item> {
    tlv::walk(region, &PARAMS)
        .into_iter()
        .map(|r| match namer(r.tag) {
            Some(n) => Item::bytes(n, r.tag, r.value),
            None => Item::unknown(r.tag, r.value),
        })
        .collect()
}

/// §3.3.2: INIT and INIT_ACK carry twenty octets of their own before the
/// parameters, of which the four the chunk header already spent are not in the
/// value.
const INIT_FIXED: &[(&str, usize, usize)] = &[
    ("init_tag", 0, 4),
    ("a_rwnd", 4, 4),
    ("n_out_streams", 8, 2),
    ("n_in_streams", 10, 2),
    ("init_tsn", 12, 4),
];

fn init_body(v: &[u8]) -> Vec<Item> {
    let mut out: Vec<Item> = INIT_FIXED
        .iter()
        .map(|(n, at, w)| Item::uint(n, 0, tlv::be(v.get(*at..at + w).unwrap_or(&[]))))
        .collect();
    out.extend(items(v.get(16..).unwrap_or(&[]), param_name));
    out
}

fn parse_options(hdr: &[u8]) -> Vec<Item> {
    let region = hdr.get(12..).unwrap_or(&[]);
    tlv::walk(region, &CHUNKS)
        .into_iter()
        .map(|r| {
            let name = chunk_name(r.tag);
            let nested = match r.tag {
                1 | 2 => Some(init_body(r.value)),
                4 | 5 => Some(items(r.value, param_name)),
                6 | 9 => Some(items(r.value, cause_name)),
                _ => None,
            };
            match (name, nested) {
                (Some(n), Some(sub)) => Item::named(n, r.tag, ItemValue::Items(sub)),
                (Some(n), None) => Item::bytes(n, r.tag, r.value),
                (None, _) => Item::unknown(r.tag, r.value),
            }
        })
        .collect()
}
