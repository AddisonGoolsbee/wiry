//! RFC 9260 §3.1: the common header is a 16-bit source port, a 16-bit destination
//! port, a 32-bit verification tag and a 32-bit checksum. §3.2 gives the chunk
//! format that follows it: a one-octet type, a one-octet flags field, a 16-bit
//! length counting the type, flags and length octets themselves, and a value
//! padded out to a four-octet boundary. Chunk types from the IANA "Stream Control
//! Transmission Protocol (SCTP) Parameters" registry.
//!
//! §3.2.1 gives a chunk *parameter* the same shape at sixteen bits, and §3.3.10
//! gives an error cause the same shape again with a number space of its own, so a
//! chunk that carries either reads as a nested item list: INIT and INIT_ACK as
//! their twenty octets of §3.3.2 followed by their parameters, HEARTBEAT and its
//! acknowledgement as parameters, ABORT and ERROR as causes. Every other chunk
//! keeps its octets, because nothing says they are TLVs.
//!
//! Generated by dev/protogen from dev/protogen/specs/sctp.toml. Field layouts
//! come from the RFC cited above; edit the spec, not this file.

