#[cfg(test)]
mod tests {
    #![allow(unused_imports)]
    use super::*;
    use crate::field::FieldValue;
    use crate::packet::Packet;

    // protogen:tests begin
    /// RFC 2328 §A.3.2 hello, hand-built: router 10.0.0.1, area 0.0.0.0, length 24.
    fn vector() -> Vec<u8> {
        vec![
            0x02, 0x01, 0x00, 0x18, 0x0a, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
            0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        ]
    }

    #[test]
    fn dissects_the_rfc_vector() {
        let p = Packet::dissect(vector(), ProtoId::Ospf);
        let l = p.find_layer(ProtoId::Ospf).unwrap();
        assert_eq!(p.get(l, "version").unwrap(), FieldValue::Uint(2));
        assert_eq!(p.get(l, "type").unwrap(), FieldValue::Uint(1));
        assert_eq!(p.get(l, "len").unwrap(), FieldValue::Uint(24));
        assert_eq!(p.get(l, "chksum").unwrap(), FieldValue::Uint(0));
        assert_eq!(p.get(l, "authtype").unwrap(), FieldValue::Uint(0));
        assert_eq!(p.raw_bytes(), &vector()[..]);
    }

    #[test]
    fn truncation_does_not_panic() {
        for n in 0..vector().len() {
            let p = Packet::dissect(vector()[..n].to_vec(), ProtoId::Ospf);
            assert_eq!(p.raw_bytes(), &vector()[..n]);
        }
    }

    #[test]
    fn writes_survive_a_rebuild() {
        let mut p = Packet::dissect(vector(), ProtoId::Ospf);
        let l = p.find_layer(ProtoId::Ospf).unwrap();
        let n = p.raw_bytes().len();
        for f in crate::proto::active_fields(ProtoId::Ospf, false, p.header(l))
            .filter(|f| f.kind == crate::field::FieldKind::Uint && f.bit_len <= 32)
            .map(|f| f.name)
            .collect::<Vec<_>>()
        {
            p.set_uint(l, f, 1);
        }
        assert_eq!(p.to_bytes().len(), n);
    }

    fn hello() -> Vec<u8> {
        let mut v = vector();
        v[3] = 48;
        v.extend_from_slice(&[
            0xff, 0xff, 0xff, 0x00, 0x00, 0x0a, 0x02, 0x01, 0x00, 0x00, 0x00, 0x28, 0x0a, 0x00,
            0x00, 0x01, 0x00, 0x00, 0x00, 0x00, 0x0a, 0x00, 0x00, 0x02,
        ]);
        v
    }

    #[test]
    fn the_type_octet_reaches_the_body_layer() {
        let p = Packet::dissect(hello(), ProtoId::Ospf);
        assert_eq!(
            p.layers().iter().map(|s| s.proto).collect::<Vec<_>>(),
            vec![ProtoId::Ospf, ProtoId::OspfHello]
        );
        let l = p.find_layer(ProtoId::OspfHello).unwrap();
        assert_eq!(p.options(l).unwrap().len(), 1);
    }

    /// RFC 2328 §A.3.1: `len` covers the header and the body, so octets past it
    /// are not part of the hello however well formed they look.
    #[test]
    fn the_packet_length_bounds_the_body() {
        let mut data = hello();
        data.extend_from_slice(&[10, 0, 0, 3]);
        let p = Packet::dissect(data, ProtoId::Ospf);
        let l = p.find_layer(ProtoId::OspfHello).unwrap();
        assert_eq!(p.options(l).unwrap().len(), 1);
        assert!(p.find_layer(ProtoId::Padding).is_some());
    }

    /// RFC 2328 §D.3 gives the 64 authentication bits a structure only when the
    /// type is 2, so reading `keyid` from a null-authenticated packet would be
    /// reading the opaque authentication data.
    #[test]
    fn the_crypto_authentication_fields_appear_only_for_type_two() {
        let p = Packet::dissect(vector(), ProtoId::Ospf);
        let l = p.find_layer(ProtoId::Ospf).unwrap();
        assert!(p.get(l, "keyid").is_none());
        assert!(p.get(l, "authdata").is_some());

        let mut data = vector();
        data[15] = 2;
        data[18] = 7;
        let p = Packet::dissect(data, ProtoId::Ospf);
        let l = p.find_layer(ProtoId::Ospf).unwrap();
        assert_eq!(p.get(l, "keyid").unwrap(), FieldValue::Uint(7));
        assert!(p.get(l, "authdata").is_none());
    }

    #[test]
    fn every_body_type_reaches_its_own_layer() {
        for (ty, want) in [
            (1u8, ProtoId::OspfHello),
            (2, ProtoId::OspfDbDesc),
            (3, ProtoId::OspfLsReq),
            (4, ProtoId::OspfLsUpd),
            (5, ProtoId::OspfLsAck),
        ] {
            let mut data = vector();
            data[1] = ty;
            data[3] = 24 + 24;
            data.extend(std::iter::repeat_n(0u8, 24));
            let p = Packet::dissect(data, ProtoId::Ospf);
            assert!(p.find_layer(want).is_some(), "type {ty}");
        }
    }
    // protogen:tests end
}
