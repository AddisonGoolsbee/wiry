/// RFC 2328 §A.3.1: Packet length covers the header and the body.
fn content_len(hdr: &[u8]) -> usize {
    match hdr.get(2..4) {
        Some(b) => u16::from_be_bytes([b[0], b[1]]) as usize,
        None => 0,
    }
}

/// RFC 2328 §A.3.1: type 5 is the Link State Acknowledgment, the one body that
/// is nothing but LSA headers.
fn is_ls_ack(hdr: &[u8]) -> bool {
    hdr.get(1) == Some(&5)
}

/// Only the acknowledgment's body belongs to the header; every other type
/// stops at the fixed 24 octets and leaves its body opaque.
fn header_len(hdr: &[u8]) -> usize {
    if !is_ls_ack(hdr) {
        return 24;
    }
    (24 + crate::repeat::region_len(hdr, &GROUP)).min(hdr.len())
}
