fn next(hdr: &[u8]) -> Next {
    if hdr.len() < 2 {
        return Next::Raw;
    }
    match crate::field::read_bits(hdr, 8, 8) {
        1 => Next::Proto(ProtoId::OspfHello),
        2 => Next::Proto(ProtoId::OspfDbDesc),
        3 => Next::Proto(ProtoId::OspfLsReq),
        4 => Next::Proto(ProtoId::OspfLsUpd),
        5 => Next::Proto(ProtoId::OspfLsAck),
        _ => Next::Raw,
    }
}

fn bind_next(hdr: &mut [u8], p: ProtoId) {
    let v = match p {
        ProtoId::OspfHello => 1,
        ProtoId::OspfDbDesc => 2,
        ProtoId::OspfLsReq => 3,
        ProtoId::OspfLsUpd => 4,
        ProtoId::OspfLsAck => 5,
        _ => return,
    };
    if hdr.len() >= 2 {
        crate::field::write_bits(hdr, 8, 8, v);
    }
}

