//! RFC 2328 §A.3.1: every OSPF version 2 packet opens with a one-octet version, a
//! one-octet type, a 16-bit packet length, the 32-bit router id, the 32-bit area
//! id, a 16-bit checksum, a 16-bit authentication type and 64 bits of
//! authentication data. The body that follows is per-type (§A.3.2 onwards) and is
//! left opaque, except the one body that is nothing but a repeating group.
//!
//! RFC 2328 §A.3.6: a Link State Acknowledgment (type 5) is a list of 20-octet LSA
//! headers — §A.4.1: a 16-bit age, an options octet, a one-octet LS type, the link
//! state and advertising-router ids, a 32-bit sequence number, a checksum and the
//! LSA's own length — which fill the packet from octet 24 to the `len` the header
//! declares. That is a length-driven repeating group
//! (`crates/wiry-core/src/repeat.rs`); scapy writes the same rule as
//! `length_from=lambda pkt: pkt.underlayer.len - 24`. The other bodies (§A.3.2
//! onwards) stay opaque — see DEVIATIONS E1.
//!
