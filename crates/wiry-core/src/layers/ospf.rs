/// RFC 2328 §A.3.1: Packet length covers the header and the body.
fn content_len(hdr: &[u8]) -> usize {
    match hdr.get(2..4) {
        Some(b) => u16::from_be_bytes([b[0], b[1]]) as usize,
        None => 0,
    }
}

/// RFC 2328 §D.3: authentication type 2 gives the 64 authentication bits a
/// structure; every other type leaves them opaque.
fn is_crypto_auth(hdr: &[u8]) -> bool {
    matches!(hdr.get(14..16), Some([0, 2]))
}

fn is_plain_auth(hdr: &[u8]) -> bool {
    !is_crypto_auth(hdr)
}
