//! RFC 2328 §A.3.1: every OSPF version 2 packet opens with a one-octet version, a
//! one-octet type, a 16-bit packet length, the 32-bit router id, the 32-bit area
//! id, a 16-bit checksum, a 16-bit authentication type and 64 bits of
//! authentication data. §D.3 gives those 64 bits a structure when the
//! authentication type is 2 (Cryptographic): a reserved word, a key id, an
//! authentication data length and a 32-bit cryptographic sequence number, which is
//! why five of the fields here are conditional on `authtype`.
//!
//! The five bodies of §A.3.2 to §A.3.6 are separate layers, reached from `type` as
//! scapy's `bind_layers(OSPF_Hdr, ..., type=n)` reaches them: OSPF_Hello,
//! OSPF_DBDesc, OSPF_LSReq, OSPF_LSUpd and OSPF_LSAck. The packet length bounds
//! them, so each body's repeating group simply runs to the end of what this header
//! admits.
//!
//! Generated by dev/protogen from dev/protogen/specs/ospf.toml. Field layouts
//! come from the RFC cited above; edit the spec, not this file.

