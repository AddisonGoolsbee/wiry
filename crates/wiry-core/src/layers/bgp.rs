//! RFC 4271 §4.1: every BGP message opens with a 16-octet marker that is all ones,
//! a 16-bit length covering the whole message and a one-octet type (1 OPEN,
//! 2 UPDATE, 3 NOTIFICATION, 4 KEEPALIVE; 5 ROUTE-REFRESH is RFC 2918). The
//! bodies of §4.2 onwards are separate layers reached from `type`, as scapy's
//! `_bgp_dispatcher` reaches them: BGPOpen, BGPUpdate, BGPNotification and
//! BGPRouteRefresh. §4.4 gives KEEPALIVE no body at all, so type 4 has no layer.
//!
//! Generated by dev/protogen from dev/protogen/specs/bgp.toml. Field layouts
//! come from the RFC cited above; edit the spec, not this file.

