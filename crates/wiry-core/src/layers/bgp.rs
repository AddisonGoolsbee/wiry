/// RFC 4271 §4.1: Length covers the whole message, marker included.
fn content_len(hdr: &[u8]) -> usize {
    match hdr.get(16..18) {
        Some(b) => u16::from_be_bytes([b[0], b[1]]) as usize,
        None => 0,
    }
}

/// The marker is all ones on every message an RFC 4271 speaker sends, which is
/// what separates a message boundary from the middle of a stream.
pub fn looks_like(p: &[u8]) -> bool {
    p.len() >= 19 && p[..16].iter().all(|b| *b == 0xff)
}
