#[cfg(test)]
mod tests {
    #![allow(unused_imports)]
    use super::*;
    use crate::field::FieldValue;
    use crate::packet::Packet;

    // protogen:tests begin
    /// RFC 4271 §4.4 KEEPALIVE: the 16-octet marker, length 19, type 4.
    fn vector() -> Vec<u8> {
        vec![
            0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff,
            0xff, 0xff, 0x00, 0x13, 0x04,
        ]
    }

    #[test]
    fn dissects_the_rfc_vector() {
        let p = Packet::dissect(vector(), ProtoId::Bgp);
        let l = p.find_layer(ProtoId::Bgp).unwrap();
        assert_eq!(p.get(l, "len").unwrap(), FieldValue::Uint(19));
        assert_eq!(p.get(l, "type").unwrap(), FieldValue::Uint(4));
        assert_eq!(p.raw_bytes(), &vector()[..]);
    }

    #[test]
    fn truncation_does_not_panic() {
        for n in 0..vector().len() {
            let p = Packet::dissect(vector()[..n].to_vec(), ProtoId::Bgp);
            assert_eq!(p.raw_bytes(), &vector()[..n]);
        }
    }

    #[test]
    fn writes_survive_a_rebuild() {
        let mut p = Packet::dissect(vector(), ProtoId::Bgp);
        let l = p.find_layer(ProtoId::Bgp).unwrap();
        let n = p.raw_bytes().len();
        for f in crate::proto::active_fields(ProtoId::Bgp, false, p.header(l))
            .filter(|f| f.kind == crate::field::FieldKind::Uint && f.bit_len <= 32)
            .map(|f| f.name)
            .collect::<Vec<_>>()
        {
            p.set_uint(l, f, 1);
        }
        assert_eq!(p.to_bytes().len(), n);
    }

    /// RFC 4271 §4.1: the type octet chooses the body, and §4.4 gives
    /// KEEPALIVE none at all.
    #[test]
    fn the_type_octet_reaches_the_body_layer() {
        for (ty, len, body, want) in [
            (
                1u8,
                29u16,
                vec![4u8, 0, 1, 0, 180, 10, 0, 0, 1, 0],
                Some(ProtoId::BgpOpen),
            ),
            (2, 23, vec![0u8, 0, 0, 0], Some(ProtoId::BgpUpdate)),
            (3, 21, vec![6u8, 2], Some(ProtoId::BgpNotification)),
            (4, 19, vec![], None),
            (5, 23, vec![0u8, 1, 0, 1], Some(ProtoId::BgpRouteRefresh)),
        ] {
            let mut data = vector();
            data[16..18].copy_from_slice(&len.to_be_bytes());
            data[18] = ty;
            data.extend(body);
            let p = Packet::dissect(data, ProtoId::Bgp);
            match want {
                Some(w) => assert!(p.find_layer(w).is_some(), "type {ty}"),
                None => assert_eq!(p.layers().len(), 1, "type {ty}"),
            }
        }
    }
    // protogen:tests end
}
