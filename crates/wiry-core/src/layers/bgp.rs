fn next(hdr: &[u8]) -> Next {
    if hdr.len() < 19 {
        return Next::Raw;
    }
    match crate::field::read_bits(hdr, 144, 8) {
        1 => Next::Proto(ProtoId::BgpOpen),
        2 => Next::Proto(ProtoId::BgpUpdate),
        3 => Next::Proto(ProtoId::BgpNotification),
        5 => Next::Proto(ProtoId::BgpRouteRefresh),
        _ => Next::Raw,
    }
}

fn bind_next(hdr: &mut [u8], p: ProtoId) {
    let v = match p {
        ProtoId::BgpOpen => 1,
        ProtoId::BgpUpdate => 2,
        ProtoId::BgpNotification => 3,
        ProtoId::BgpRouteRefresh => 5,
        _ => return,
    };
    if hdr.len() >= 19 {
        crate::field::write_bits(hdr, 144, 8, v);
    }
}

