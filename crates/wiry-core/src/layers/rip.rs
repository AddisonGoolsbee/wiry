//! RFC 1058 §3.1 and RFC 2453 §3.6: a RIP message is a one-octet command, a
//! one-octet version and two octets that must be zero, followed by up to 25 route
//! entries. RFC 2453 §4 gives an entry as a 16-bit address family, a 16-bit route
//! tag, an IPv4 address, a subnet mask, a next hop and a 32-bit metric — twenty
//! octets, repeated to the end of the datagram. RFC 1058 §3.1 lays version 1 out at
//! the same widths and requires the tag, mask and next-hop words to be zero, so one
//! table reads both; the version 2 names are used, as scapy's are.
//!
//! The entries are a repeating group (`crates/wiry-core/src/repeat.rs`), not a
//! payload. RFC 2453 §4.1 authentication, which replaces the first entry when its
//! address family is 0xFFFF, is not decoded — see DEVIATIONS E1.
//!
//! Generated by dev/protogen from dev/protogen/specs/rip.toml. Field layouts
//! come from the RFC cited above; edit the spec, not this file.

