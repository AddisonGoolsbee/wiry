        let p = Packet::dissect(vector(), ProtoId::Rip);
        let l = p.find_layer(ProtoId::Rip).unwrap();
        assert_eq!(p.get(l, "cmd").unwrap(), FieldValue::Uint(1));
        assert_eq!(p.get(l, "version").unwrap(), FieldValue::Uint(2));
        assert_eq!(p.get(l, "null").unwrap(), FieldValue::Uint(0));
        assert_eq!(p.raw_bytes(), &vector()[..]);
