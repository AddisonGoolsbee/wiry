//! RFC 3768 §5.1: a four-bit version, a four-bit type, a one-octet virtual router
//! id, a one-octet priority, a one-octet count of IP addresses, a one-octet
//! authentication type, a one-octet advertisement interval in seconds and a 16-bit
//! checksum, followed by that many addresses — a count-driven repeating group
//! (`crates/wiry-core/src/repeat.rs`). RFC 5798 §5.1 keeps the layout for version
//! 3 but reads the two authentication octets as a reserved field and a 12-bit
//! advertisement interval in centiseconds.
//!
//! RFC 3768 §5.3.10 puts eight octets of authentication data after the address
//! list. They sit at an offset the address count decides, which the flat table
//! cannot place, so they stay in the payload (DEVIATIONS E1); scapy declares them
//! as `auth1` and `auth2`.
//!
//! Generated by dev/protogen from dev/protogen/specs/vrrp.toml. Field layouts
//! come from the RFC cited above; edit the spec, not this file.

use crate::field::FieldDesc;
