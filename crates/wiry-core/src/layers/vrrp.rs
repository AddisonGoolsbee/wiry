#[cfg(test)]
mod tests {
    #![allow(unused_imports)]
    use super::*;
    use crate::field::FieldValue;
    use crate::packet::Packet;

    // protogen:tests begin
    /// RFC 3768 §5.1 advertisement: VRID 1, priority 100, one address 10.0.0.1.
    fn vector() -> Vec<u8> {
        vec![
            0x21, 0x01, 0x64, 0x01, 0x00, 0x01, 0xba, 0x52, 0x0a, 0x00, 0x00, 0x01,
        ]
    }

    #[test]
    fn dissects_the_rfc_vector() {
        let p = Packet::dissect(vector(), ProtoId::Vrrp);
        let l = p.find_layer(ProtoId::Vrrp).unwrap();
        assert_eq!(p.get(l, "version").unwrap(), FieldValue::Uint(2));
        assert_eq!(p.get(l, "type").unwrap(), FieldValue::Uint(1));
        assert_eq!(p.get(l, "vrid").unwrap(), FieldValue::Uint(1));
        assert_eq!(p.get(l, "priority").unwrap(), FieldValue::Uint(100));
        assert_eq!(p.get(l, "ipcount").unwrap(), FieldValue::Uint(1));
        assert_eq!(p.get(l, "authtype").unwrap(), FieldValue::Uint(0));
        assert_eq!(p.get(l, "adv").unwrap(), FieldValue::Uint(1));
        assert_eq!(p.get(l, "chksum").unwrap(), FieldValue::Uint(47698));
        assert_eq!(p.raw_bytes(), &vector()[..]);
    }

    #[test]
    fn truncation_does_not_panic() {
        for n in 0..vector().len() {
            let p = Packet::dissect(vector()[..n].to_vec(), ProtoId::Vrrp);
            assert_eq!(p.raw_bytes(), &vector()[..n]);
        }
    }

    #[test]
    fn writes_survive_a_rebuild() {
        let mut p = Packet::dissect(vector(), ProtoId::Vrrp);
        let l = p.find_layer(ProtoId::Vrrp).unwrap();
        let n = p.raw_bytes().len();
        for f in crate::proto::active_fields(ProtoId::Vrrp, false, p.header(l))
            .filter(|f| f.kind == crate::field::FieldKind::Uint && f.bit_len <= 32)
            .map(|f| f.name)
            .collect::<Vec<_>>()
        {
            p.set_uint(l, f, 1);
        }
        assert_eq!(p.to_bytes().len(), n);
    }

    use crate::options::ItemValue;

    #[test]
    fn the_address_list_reads_as_a_scalar_list() {
        let mut data = vector();
        data[3] = 2;
        data.extend_from_slice(&[10, 0, 0, 2]);
        let p = Packet::dissect(data, ProtoId::Vrrp);
        let l = p.find_layer(ProtoId::Vrrp).unwrap();
        let items = p.options(l).unwrap();
        assert_eq!(items.len(), 2);
        assert_eq!(items[0].value, ItemValue::Text("10.0.0.1".into()));
        assert_eq!(items[1].value, ItemValue::Text("10.0.0.2".into()));
    }

    /// RFC 3768 §5.3.10: the authentication data after the list is outside the
    /// header, so `ipcount` and not the datagram end decides where it stops.
    #[test]
    fn octets_past_the_count_are_not_addresses() {
        let mut data = vector();
        data.extend(std::iter::repeat_n(0u8, 8));
        let p = Packet::dissect(data, ProtoId::Vrrp);
        let l = p.find_layer(ProtoId::Vrrp).unwrap();
        assert_eq!(p.options(l).unwrap().len(), 1);
        assert!(p.find_layer(ProtoId::Raw).is_some());
    }
    // protogen:tests end
}
