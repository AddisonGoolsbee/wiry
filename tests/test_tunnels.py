def test_erspan_type_one_has_no_header_of_its_own():
    body = b"\x00\x00\x88\xbe" + inner_frame()
    pkt = Ether(bytes(Ether() / IP(proto=47) / Raw(load=body)))
    assert pkt.layers() == ["Ether", "IP", "GRE", "Ether", "IP", "TCP"]


def test_erspan_type_three_optional_subheader():
    for o in (0, 1):
        body = b"\x00\x00\x22\xeb"
        body += b"\x20\x64\x00\x05" + b"\x11\x22\x33\x44" + bytes([0, 0, 0, o])
        if o:
            body += b"\xde\xad\xbe\xef\x00\x00\x00\x00"
        body += inner_frame()
        pkt = Ether(bytes(Ether() / IP(proto=47) / Raw(load=body)))
        assert pkt.layers() == ["Ether", "IP", "GRE", "ERSPAN_III", "Ether", "IP", "TCP"]
        assert pkt[ERSPAN_III].timestamp == 0x11223344
        assert pkt[ERSPAN_III].o == o
        # Only a header measured against the O bit lands the frame right here.
        assert pkt[Ether:2].dst == "33:33:33:33:33:33"


# --- Nesting, round-trip, and the bulk path ---------------------------------


def test_a_tunnel_inside_a_tunnel_inside_a_tunnel():
    pkt = Ether() / IP(dst="10.0.0.1") / GRE()
    pkt = pkt / IP(dst="10.0.0.2") / UDP() / VXLAN(vni=5)
    pkt = pkt / Ether() / IP(dst="10.0.0.3") / TCP(dport=443)
    back = Ether(bytes(pkt))
    assert back.layers() == [
        "Ether", "IP", "GRE", "IP", "UDP", "VXLAN", "Ether", "IP", "TCP",
    ]
    assert [back[IP:i].dst for i in (1, 2, 3)] == ["10.0.0.1", "10.0.0.2", "10.0.0.3"]
    assert back[TCP].dport == 443


def test_an_arbitrarily_nested_capture_is_bounded():
    body = bytes(Ether() / IP() / TCP())
    for _ in range(100):
        body = b"\x00\x00\x65\x58" + body
        body = ip4(47, body)
    pkt = Ether(bytes(Ether() / Raw(load=body)))
    assert len(pkt.layers()) <= 33
    assert bytes(pkt) == bytes(Ether() / Raw(load=body))


