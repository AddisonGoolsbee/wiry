def tunnel_capture():
    return [
        Ether() / IP(dst="10.0.0.1") / UDP() / VXLAN(vni=1)
        / Ether() / IP(dst="192.168.0.1") / TCP(dport=80),
        Ether() / IP(dst="10.0.0.2") / GRE() / IP(dst="192.168.0.2") / TCP(dport=443),
        Ether() / IP(dst="10.0.0.3") / TCP(dport=22),
        Ether() / IPv6() / IPv6ExtHdrHopByHop() / UDP(dport=546),
    ]


def test_the_bulk_path_sees_inner_layers_and_agrees_with_the_loop(tmp_path):
    path = str(tmp_path / "tunnels.pcap")
    wrpcap(path, tunnel_capture())
    cap = rdpcap(path)

    specs = [("IP", "dst"), ("TCP", "dport"), ("VXLAN", "vni"), ("GRE", "proto")]
    cols = cap.columns(specs)
    for layer, field in specs:
        want = [
            getattr(pkt[layer], field) if pkt.haslayer(layer) else None for pkt in cap
        ]
        assert cols[f"{layer}.{field}"] == want, f"{layer}.{field}"

    # The bulk path must not quietly report the inner tunnel endpoint for the
    # outer one: IP.dst names the first, the rest are reachable by index.
    assert cols["IP.dst"] == ["10.0.0.1", "10.0.0.2", "10.0.0.3", None]
    assert cols["VXLAN.vni"] == [1, None, None, None]


def test_filtering_on_an_inner_layer_selects_in_the_engine(tmp_path):
    path = str(tmp_path / "tunnels.pcap")
    wrpcap(path, tunnel_capture())
    cap = rdpcap(path)
    got = cap.filter([("VXLAN", "vni", 1)])
    assert len(got) == 1
    assert got[0].haslayer(VXLAN)
    assert [p.summary() for p in cap.filter([("GRE", "proto", 0x0800)])] == [
        "Ether / IP / GRE / IP / TCP"
    ]


# --- Lengths no field can hold are refused, never wrapped -------------------


def padn(n):
    """RFC 8200 §4.2 PadN blocks totalling n octets."""
    out = b""
    while n > 0:
        k = min(n, 257)
        if k == 1:
            out += b"\x00"
            n -= 1
            continue
        out += b"\x01" + bytes([k - 2]) + b"\x00" * (k - 2)
        n -= k
    return out


def test_a_geneve_option_block_wider_than_six_bits_is_refused():
    # RFC 8926 §3.1: Opt Len is six bits of 4-octet words, so 252 octets is the
    # most it can name. 256 used to write 64 & 0x3f == 0 and swallow the block.
    ok = Ether() / IP() / UDP() / GENEVE(options=b"\xaa" * 252) / Ether() / IP() / TCP()
    assert Ether(bytes(ok))[GENEVE].optionlen == 63
    assert Ether(bytes(ok)).layers()[-1] == "TCP"
    with pytest.raises(ValueError, match="GENEVE.optionlen"):
        bytes(Ether() / IP() / UDP() / GENEVE(options=b"\xaa" * 256) / Ether() / IP())


def test_an_extension_header_wider_than_eight_bits_is_refused():
    # RFC 8200 §4.3: Hdr Ext Len is eight bits of 8-octet units, so 2046 octets
    # of options is the most it can name; 2054 used to clamp to 255 and read the
    # eight octets past the claim as the transport header.
    ok = Ether() / IPv6() / IPv6ExtHdrDestOpt(options=padn(2046)) / UDP()
    assert Ether(bytes(ok))[IPv6ExtHdrDestOpt].len == 255
    assert Ether(bytes(ok)).layers()[-1] == "UDP"
    with pytest.raises(ValueError, match="IPv6ExtHdrDestOpt.len"):
        bytes(Ether() / IPv6() / IPv6ExtHdrDestOpt(options=padn(2054)) / UDP())


def test_a_pppoe_payload_wider_than_sixteen_bits_is_refused():
    # RFC 2516 §4: LENGTH is sixteen bits and nothing encloses PPPoE that would
    # catch the overflow, so 70000 octets used to emit 70002 % 65536 == 4466.
    with pytest.raises(ValueError, match="PPPoE.len"):
        bytes(Ether() / PPPoE() / PPP() / Raw(load=b"x" * 70000))
    with pytest.raises(ValueError, match="GTP_U_Header.length"):
        bytes(Ether() / GTP_U_Header() / Raw(load=b"x" * 70000))


# --- A clipped capture keeps the lengths the wire gave (E12) ----------------


def clipped_hop_by_hop():
    """IPv6 claiming 200 payload octets, carrying 24 of a 48-octet header."""
    payload = bytes([17, 5]) + b"\x01\x00" * 11
    return bytes(Ether() / IPv6(plen=200, nh=0)) + payload


def test_editing_a_clipped_capture_does_not_shrink_an_extension_header_length():
    raw = clipped_hop_by_hop()
    pkt = Ether(raw)
    assert pkt[IPv6ExtHdrHopByHop].len == 5
    pkt[IPv6].hlim = 1
    assert Ether(bytes(pkt))[IPv6ExtHdrHopByHop].len == 5


def test_editing_a_clipped_capture_does_not_shrink_a_geneve_option_length():
    # Opt Len 16 words = 64 octets of options, of which 20 were captured.
    body = b"\x10\x00\x65\x58\x00\x00\x01\x00" + b"\xaa" * 20
    raw = bytes(Ether() / IP(len=20 + 8 + 200) / UDP(sport=40000, dport=6081, len=208)) + body
    pkt = Ether(raw)
    assert pkt[GENEVE].optionlen == 16
    pkt[IP].ttl = 3
    assert Ether(bytes(pkt))[GENEVE].optionlen == 16


# --- ERSPAN Type II is told from Type I by GRE's sequence bit ---------------


def test_stacking_erspan_type_two_sets_the_gre_sequence_bit():
    # draft-foschiano-erspan-03 §4. Without it the built frame dissects back as
    # a bare Type I and the mirrored frame reads eight octets out of place.
    pkt = Ether() / IP() / GRE() / ERSPAN_II(session_id=5) / Ether() / IP() / TCP()
    back = Ether(bytes(pkt))
    assert back.layers() == ["Ether", "IP", "GRE", "ERSPAN_II", "Ether", "IP", "TCP"]
    assert back[GRE].seqnum_present == 1
    assert back[ERSPAN_II].session_id == 5
    # Type III is reached by its own EtherType, so the bit stays clear.
    three = Ether(bytes(Ether() / IP() / GRE() / ERSPAN_III() / Ether() / IP() / TCP()))
    assert three.layers() == ["Ether", "IP", "GRE", "ERSPAN_III", "Ether", "IP", "TCP"]
    assert three[GRE].seqnum_present == 0


