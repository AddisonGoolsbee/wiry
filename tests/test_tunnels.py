"""Encapsulation layers: the chain must not stop at the tunnel.

Vectors are laid out from the RFC field diagrams cited above each one. Nothing
here is generated by running another packet library.
"""

import struct

import pytest

from wiry import (
    ERSPAN_II, ERSPAN_III, Ether, GENEVE, GRE, GTP_U_Header, IP, IPv6,
    IPv6ExtHdrDestOpt, IPv6ExtHdrFragment, IPv6ExtHdrHopByHop,
    IPv6ExtHdrRouting, MPLS, PPP, PPPoE, PPPoED, Raw, TCP, UDP, VXLAN, rdpcap,
    wrpcap,
)


def ip4(proto, payload, src="10.0.0.1", dst="10.0.0.2"):
    return bytes(IP(src=src, dst=dst, proto=proto) / Raw(load=payload))


def inner_frame(dst="33:33:33:33:33:33"):
    return bytes(Ether(dst=dst, src="44:44:44:44:44:44") / IP(src="192.168.1.1") / TCP(dport=443))


# --- IPv6 extension headers, RFC 8200 §4 -----------------------------------


@pytest.mark.parametrize(
    "nh,cls,name",
    [
        (0, IPv6ExtHdrHopByHop, "IPv6ExtHdrHopByHop"),
        (60, IPv6ExtHdrDestOpt, "IPv6ExtHdrDestOpt"),
    ],
)
def test_an_option_header_is_walked_to_the_transport(nh, cls, name):
    # RFC 2711 §2.1 Router Alert, then PadN to fill the 8-octet unit.
    opts = b"\x05\x02\x00\x00\x01\x00"
    payload = bytes([17]) + b"\x00" + opts + bytes(UDP(sport=1234, dport=80))
    pkt = Ether(bytes(Ether() / IPv6(nh=nh) / Raw(load=payload)))
    assert pkt.layers() == ["Ether", "IPv6", name, "UDP"]
    assert pkt[name].nh == 17
    assert pkt[name].len == 0
    assert pkt[UDP].dport == 80


def test_a_routing_header_names_its_type_and_segments_left():
    # RFC 8200 §4.4 Type 0, one address, segments left 1.
    payload = bytes([6, 0x02, 0x00, 0x01, 0, 0, 0, 0]) + b"\x20\x01\x0d\xb8" + bytes(12)
    payload += bytes(TCP(dport=22))
    pkt = Ether(bytes(Ether() / IPv6(nh=43) / Raw(load=payload)))
    assert pkt.layers() == ["Ether", "IPv6", "IPv6ExtHdrRouting", "TCP"]
    assert pkt[IPv6ExtHdrRouting].type == 0
    assert pkt[IPv6ExtHdrRouting].segleft == 1
    assert pkt[TCP].dport == 22


def test_a_later_fragment_carries_no_transport_header():
    # RFC 8200 §4.5: offset 23 eight-octet units, M clear.
    payload = bytes([6, 0x00, 0x00, 0xB8, 0, 0, 0, 7]) + bytes(TCP())
    pkt = Ether(bytes(Ether() / IPv6(nh=44) / Raw(load=payload)))
    assert pkt.layers() == ["Ether", "IPv6", "IPv6ExtHdrFragment", "Raw"]
    assert pkt[IPv6ExtHdrFragment].offset == 23
    assert pkt[IPv6ExtHdrFragment].m == 0


def test_a_first_fragment_still_reaches_the_transport():
    payload = bytes([6, 0x00, 0x00, 0x01, 0, 0, 0, 7]) + bytes(TCP(dport=8080))
    pkt = Ether(bytes(Ether() / IPv6(nh=44) / Raw(load=payload)))
    assert pkt.layers() == ["Ether", "IPv6", "IPv6ExtHdrFragment", "TCP"]
    assert pkt[TCP].dport == 8080


def test_an_extension_chain_builds_and_reads_back():
    pkt = Ether() / IPv6() / IPv6ExtHdrHopByHop() / IPv6ExtHdrFragment(id=9) / UDP(dport=53)
    back = Ether(bytes(pkt))
    assert back.layers() == [
        "Ether", "IPv6", "IPv6ExtHdrHopByHop", "IPv6ExtHdrFragment", "UDP",
    ]
    assert back[IPv6].nh == 0
    assert back[IPv6ExtHdrHopByHop].nh == 44
    assert back[IPv6ExtHdrFragment].nh == 17
    assert back[IPv6ExtHdrFragment].id == 9
    # RFC 8200 §3: everything past the fixed header, extension headers included.
    assert back[IPv6].plen == len(bytes(pkt)) - 14 - 40


# --- GRE, RFC 2784 / RFC 2890 ----------------------------------------------


def test_gre_carries_a_datagram():
    pkt = Ether(bytes(Ether() / IP() / GRE() / IP(src="192.168.1.1") / TCP(dport=443)))
    assert pkt.layers() == ["Ether", "IP", "GRE", "IP", "TCP"]
    assert pkt[GRE].proto == 0x0800
    assert pkt[IP:2].src == "192.168.1.1"
    assert pkt[TCP].dport == 443


def test_gre_key_and_sequence_move_the_fields_that_follow():
    pkt = Ether() / IP() / GRE(key_present=1, seqnum_present=1, key=0x11223344, seqnum=9)
    pkt = pkt / IP() / UDP()
    back = Ether(bytes(pkt))
    assert back.layers() == ["Ether", "IP", "GRE", "IP", "UDP"]
    assert back[GRE].key == 0x11223344
    assert back[GRE].seqnum == 9


def test_gre_carries_a_whole_frame_under_transparent_ethernet_bridging():
    payload = b"\x00\x00\x65\x58" + inner_frame()
    pkt = Ether(bytes(Ether() / IP(proto=47) / Raw(load=payload)))
    assert pkt.layers() == ["Ether", "IP", "GRE", "Ether", "IP", "TCP"]
    assert pkt[Ether:2].dst == "33:33:33:33:33:33"


