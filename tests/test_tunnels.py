@pytest.mark.parametrize("name", sorted(truncation_corpus()))
def test_every_layer_survives_a_cut_at_every_offset(name):
    raw = truncation_corpus()[name]
    for cut in range(len(raw) + 1):
        want = raw[:cut]
        pkt = Ether(want)
        assert bytes(pkt) == want, f"{name} cut={cut}"
        # The write half needs its own coverage: a read-only sweep leaves every
        # recomputation unexercised, which is where the panics lived before.
        pkt.summary()
        pkt.show()
        again = Ether(want)
        for layer in dict.fromkeys(again.layers()):
            obj = again[layer]
            for field in obj.fields():
                value = getattr(obj, field)
                if isinstance(value, int):
                    setattr(obj, field, value)
        bytes(again)
