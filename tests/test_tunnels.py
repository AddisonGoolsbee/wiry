def test_erspan_type_two_carries_the_mirrored_frame():
    body = b"\x10\x00\x88\xbe" + b"\x00\x00\x00\x01"
    body += b"\x10\x64\x00\x05" + b"\x00\x00\x00\x09" + inner_frame()
    pkt = Ether(bytes(Ether() / IP(proto=47) / Raw(load=body)))
    assert pkt.layers() == ["Ether", "IP", "GRE", "ERSPAN_II", "Ether", "IP", "TCP"]
