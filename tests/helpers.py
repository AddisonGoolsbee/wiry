"""Hand-built byte vectors and a pure-Python internet checksum.

Every vector is laid out from the RFC / IEEE field diagram cited above it.
Nothing here is generated by running another packet library.
"""

import struct


def checksum(data: bytes) -> int:
    """Internet checksum, RFC 1071."""
    if len(data) % 2:
        data += b"\x00"
    total = 0
    for i in range(0, len(data), 2):
        total += (data[i] << 8) | data[i + 1]
        total = (total & 0xFFFF) + (total >> 16)
    return (~total) & 0xFFFF


def pseudo_v4(src: bytes, dst: bytes, proto: int, length: int) -> bytes:
    """IPv4 transport pseudo-header, RFC 9293 §3.1 / RFC 768."""
    return src + dst + b"\x00" + bytes([proto]) + struct.pack("!H", length)


def pseudo_v6(src: bytes, dst: bytes, nh: int, length: int) -> bytes:
    """IPv6 upper-layer pseudo-header, RFC 8200 §8.1."""
    return src + dst + struct.pack("!I", length) + b"\x00\x00\x00" + bytes([nh])


