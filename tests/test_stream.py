"""TCP stream reassembly, RFC 9293 §3.4 and §3.7.

Every packet here is built from wiry's own layers, so the sequence numbers and
flags are the RFC's and nothing is generated by running another library.
"""

import os
import tempfile

import pytest

from wiry import (
    IP,
    TCP,
    Ether,
    IPv6,
    PacketList,
    Raw,
    TCPSession,
    DefaultSession,
    IPSession,
    UDP,
    rdpcap,
    sniff,
    wrpcap,
)
from wiry.stream import LOSSY, SAW_FIN, SAW_SYN, streams

REQUEST = (
    b"GET /index.html HTTP/1.1\r\n"
    b"Host: example.io\r\n"
    b"User-Agent: wiry\r\n"
    b"Accept: */*\r\n"
    b"\r\n"
)

RECORD = bytes([0x16, 0x03, 0x01, 0x00, 0x20]) + bytes(range(0x20))


def seg(seq, data=b"", flags="PA", sport=1234, dport=80, back=False):
    a, b = ("10.0.0.1", "10.0.0.2") if not back else ("10.0.0.2", "10.0.0.1")
    if back:
        sport, dport = dport, sport
    p = Ether() / IP(src=a, dst=b) / TCP(sport=sport, dport=dport, seq=seq, flags=flags)
    return p / Raw(load=data) if data else p


def capture(packets):
    """Through a real pcap, so the bulk path reads a capture buffer."""
    path = tempfile.mktemp(suffix=".pcap")
    try:
        wrpcap(path, packets)
        return rdpcap(path)
    finally:
        if os.path.exists(path):
            os.remove(path)


def _payload(pkt):
    """Octets after Ether/IP/TCP with no options: 14 + 20 + 20."""
    return bytes(pkt)[54:]


def only(pl):
    s = streams(pl)
    assert len(s) == 1
    return s[next(iter(s))]


def test_segments_in_order_become_one_stream():
    s = only(capture([seg(100, b"GET "), seg(104, b"/ HTTP/1.1\r\n\r\n")]))
    assert s.client.data == b"GET / HTTP/1.1\r\n\r\n"
    assert s.key == "TCP 10.0.0.1:1234 > 10.0.0.2:80"
    assert s.src == "10.0.0.1" and s.sport == 1234
    assert s.dst == "10.0.0.2" and s.dport == 80
    assert s.client.complete and s.complete


def test_the_two_directions_are_kept_apart():
    s = only(capture([seg(1, b"up"), seg(9, b"down", back=True), seg(3, b"!")]))
    assert s.client.data == b"up!"
    assert s.server.data == b"down"
    assert s.forward.data == s.client.data
    assert s.backward.data == s.server.data


def test_out_of_order_segments_are_put_back_in_order():
    s = only(capture([seg(30, b"ccc"), seg(24, b"aaa"), seg(27, b"bbb")]))
    assert s.client.data == b"aaabbbccc"
    assert s.client.gaps == []


def test_a_retransmission_is_delivered_once():
    s = only(capture([seg(5, b"hello"), seg(5, b"hello"), seg(10, b" world")]))
    assert s.client.data == b"hello world"


def test_an_overlapping_retransmission_keeps_the_first_writer():
    """The overlap policy, stated in the module header and asserted here: a
    later segment never rewrites an octet an earlier one delivered."""
    s = only(capture([seg(0, b"AAAA"), seg(2, b"XXXXBB")]))
    assert s.client.data == b"AAAAXXBB"


def test_a_gap_is_named_and_never_filled_in():
    s = only(capture([seg(0, b"head"), seg(1000, b"tail")]))
    assert s.client.data == b"headtail"
    assert s.client.gaps == [(4, 996)]
    assert not s.client.complete


def test_the_sequence_space_wraps():
    s = only(
        capture(
            [
                seg(0xFFFFFFF8, b"before"),
                seg(0xFFFFFFFE, b"after"),
                seg(3, b"!"),
            ]
        )
    )
    assert s.client.data == b"beforeafter!"
    assert s.client.gaps == []


def test_a_syn_consumes_one_sequence_number():
    s = only(capture([seg(99, flags="S"), seg(100, b"data")]))
    assert s.client.data == b"data"
    assert s.client.gaps == []
    assert s.client.flags & SAW_SYN


def test_a_fin_is_recorded():
    s = only(capture([seg(1, b"bye", flags="FA")]))
    assert s.client.flags & SAW_FIN


def test_a_segment_far_past_the_frontier_is_refused():
    s = only(capture([seg(0, b"hi"), seg(0x200000, b"far")]))
    assert s.client.data == b"hi"
    assert s.client.flags & LOSSY
    assert s.client.dropped == 3


def test_provenance_maps_an_offset_back_to_its_packet():
    pl = capture([seg(0, b"aaaa"), seg(9, b"zz", back=True), seg(4, b"bbbb")])
    s = only(pl)
    assert s.client.segments == [(0, 4, 0), (4, 4, 2)]
    assert s.client.packet_at(0) == 0
    assert s.client.packet_at(5) == 2
    assert s.client.packet_at(99) is None
    assert [bytes(p) for p in s.packets()] == [bytes(p) for p in pl]


def test_a_capture_with_no_tcp_has_no_streams():
    assert len(streams(capture([Ether() / IP() / UDP() / Raw(load=b"x")]))) == 0


def test_a_truncated_frame_is_not_a_panic():
    full = bytes(seg(7, bytes(range(60))))
    for cut in range(len(full)):
        pl = PacketList(_wiry_dissect(full[:cut]))
        assert isinstance(len(streams(pl)), int)


def _wiry_dissect(data):
    from wiry import _wiry as _b

    path = tempfile.mktemp(suffix=".pcap")
    try:
        with open(path, "wb") as f:
            f.write(
                b"\xd4\xc3\xb2\xa1\x02\x00\x04\x00" + bytes(8)
                + (262144).to_bytes(4, "little") + (1).to_bytes(4, "little")
            )
            f.write(bytes(8) + len(data).to_bytes(4, "little"))
            f.write(len(data).to_bytes(4, "little") + data)
        return _b.read_pcap(path)
    finally:
        if os.path.exists(path):
            os.remove(path)


# --- the application-layer payoff ------------------------------------------


def split(data, at):
    """`data` cut into segments at the given lengths, starting at sequence 1."""
    out = []
    seq = 1
    for n in at:
        out.append(seg(seq, data[:n]))
        data, seq = data[n:], seq + n
    if data:
        out.append(seg(seq, data))
    return out


def test_an_http_request_split_over_segments_is_one_message():
    pl = capture(split(REQUEST, [10, 20, 15]))
    # No one segment is an HTTP message.
    assert all(p.layers()[-1] == "Raw" for p in pl)
    s = only(pl)
    assert s.client.app == "HTTP"
    assert s.client.messages() == [REQUEST]
    parsed = s.client.parsed()
    assert [p.layers() for p in parsed] == [["HTTP"]]
    assert dict(parsed[0]["HTTP"].headers)["Host"] == "example.io"


def test_a_tls_record_split_over_segments_is_one_record():
    pl = capture(
        [
            seg(1, RECORD[:3], dport=443),
            seg(4, RECORD[3:], dport=443),
        ]
    )
    s = only(pl)
    assert s.client.app == "TLS"
    assert s.client.messages() == [RECORD]
    assert [p.layers() for p in s.client.parsed()] == [["TLS"]]


def test_two_messages_in_one_stream_are_two_messages():
    pl = capture(split(REQUEST + REQUEST, [30, 40, 20]))
    assert only(pl).client.messages() == [REQUEST, REQUEST]


def test_a_message_with_a_body_takes_its_content_length():
    body = b"POST /p HTTP/1.1\r\nContent-Length: 5\r\n\r\nhello"
    assert only(capture(split(body, [12, 20]))).client.messages() == [body]


def test_an_incomplete_message_is_not_a_message():
    assert only(capture(split(REQUEST[:-2], [10, 20]))).client.messages() == []


# --- the session surface ----------------------------------------------------


def test_tcp_session_hands_on_one_packet_per_reassembled_message():
    path = tempfile.mktemp(suffix=".pcap")
    try:
        wrpcap(path, split(REQUEST, [10, 20, 15]))
        plain = sniff(offline=path)
        assert [p.layers()[-1] for p in plain] == ["Raw"] * len(plain)
        out = sniff(offline=path, session=TCPSession)
        assert len(out) == 1
        assert out[0].layers() == ["Ether", "IP", "TCP", "HTTP"]
        assert dict(out[0]["HTTP"].headers)["Host"] == "example.io"
        assert _payload(out[0]) == REQUEST
        # The recomputed IPv4 length describes the frame it is in.
        assert out[0][IP].len == len(bytes(out[0])) - 14
    finally:
        os.remove(path)


def test_a_session_instance_and_a_session_class_agree():
    path = tempfile.mktemp(suffix=".pcap")
    try:
        wrpcap(path, split(REQUEST, [10, 20, 15]))
        a = sniff(offline=path, session=TCPSession)
        b = sniff(offline=path, session=TCPSession(app=True))
        assert [bytes(p) for p in a] == [bytes(p) for p in b]
        assert [bytes(p) for p in sniff(offline=path, session=TCPSession(app=False))] == [
            bytes(p) for p in sniff(offline=path, session=DefaultSession)
        ]
    finally:
        os.remove(path)


def test_a_session_leaves_everything_it_did_not_reassemble_alone():
    pkts = split(REQUEST, [10, 20, 15]) + [
        Ether() / IP() / UDP() / Raw(load=b"elsewhere"),
        seg(500, b"\x00\x01\x02", sport=9, dport=9),
    ]
    path = tempfile.mktemp(suffix=".pcap")
    try:
        wrpcap(path, pkts)
        out = sniff(offline=path, session=TCPSession)
        assert [p.layers()[-1] for p in out] == ["HTTP", "Raw", "Raw"]
    finally:
        os.remove(path)


def test_the_capture_filter_runs_before_the_session():
    pkts = split(REQUEST, [10, 20, 15]) + [Ether() / IP() / UDP() / Raw(load=b"x")]
    path = tempfile.mktemp(suffix=".pcap")
    try:
        wrpcap(path, pkts)
        out = sniff(offline=path, session=TCPSession, where=("IP", "proto", 6))
        assert [p.layers()[-1] for p in out] == ["HTTP"]
    finally:
        os.remove(path)


def test_ip_session_reassembles_fragments():
    from wiry import fragment

    whole = Ether() / IP(dst="10.0.0.2") / UDP() / Raw(load=bytes(range(256)))
    path = tempfile.mktemp(suffix=".pcap")
    try:
        wrpcap(path, fragment(whole, 64))
        out = sniff(offline=path, session=IPSession)
        assert len(out) == 1
        assert bytes(out[0]) == bytes(whole)
    finally:
        os.remove(path)


def test_a_session_on_a_live_sniff_says_so_rather_than_guessing():
    with pytest.raises(NotImplementedError, match="offline"):
        sniff(iface="lo0", session=TCPSession, count=1)


def test_an_object_that_is_not_a_session_is_refused():
    path = tempfile.mktemp(suffix=".pcap")
    try:
        wrpcap(path, [seg(1, b"x")])
        with pytest.raises(TypeError, match="process"):
            sniff(offline=path, session=object())
    finally:
        os.remove(path)


