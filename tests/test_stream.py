def test_the_bulk_path_and_the_per_packet_path_agree():
    """The engine is the same one either way; a capture read as a file and the
    same packets handed over one at a time must reassemble identically."""
    pkts = (
        split(REQUEST, [10, 20, 15])
        + [seg(9, b"HTTP/1.1 200 OK\r\nContent-Length: 2\r\n\r\nhi", back=True)]
        + [seg(1, b"GET ")]
    )
    pl = capture(pkts)
    bulk = streams(pl)
    one_at_a_time = streams(capture(list(pl)))
    assert list(bulk) == list(one_at_a_time)
    for k in bulk:
        for d in ("client", "server"):
            a, b = getattr(bulk[k], d), getattr(one_at_a_time[k], d)
            assert a.data == b.data
            assert a.segments == b.segments
            assert a.gaps == b.gaps


def test_the_session_output_carries_the_octets_the_streams_report():
    path = tempfile.mktemp(suffix=".pcap")
    try:
        wrpcap(path, split(REQUEST + REQUEST, [7, 33, 41]))
        pl = rdpcap(path)
        want = only(pl).client.messages()
        out = sniff(offline=path, session=TCPSession)
        assert [_payload(p) for p in out] == want
    finally:
        os.remove(path)


def test_an_ipv6_stream_reassembles_too():
    a = Ether() / IPv6(src="2001:db8::1", dst="2001:db8::2")
    pkts = [
        a / TCP(sport=1234, dport=80, seq=1, flags="PA") / Raw(load=REQUEST[:20]),
        a / TCP(sport=1234, dport=80, seq=21, flags="PA") / Raw(load=REQUEST[20:]),
    ]
    s = only(capture(pkts))
    assert s.client.data == REQUEST
    assert s.key == "TCP 2001:db8::1:1234 > 2001:db8::2:80"


def _model(segments, origin):
    """The rule spelled out longhand: the first segment to claim a stream
    offset owns it, whatever order and overlap the claims arrive in, and the
    result is every claimed octet in ascending order with nothing invented for
    the ones that were never claimed."""
    owned: dict[int, int] = {}
    for seq, data in segments:
        for i, b in enumerate(data):
            owned.setdefault(seq - origin + i, b)
    return bytes(owned[k] for k in sorted(owned))


def test_reassembly_matches_the_overlap_rule_spelled_out():
    import random

    rng = random.Random(0x2545F491)
    for round_ in range(150):
        base = 1_000_000 + rng.randrange(1 << 20)
        # Every claim is at or after `base`, so the opening window cannot fix
        # the origin above a segment that arrives later.
        claims = [(base, bytes([rng.randrange(256)]) * rng.randrange(1, 40))]
        for _ in range(rng.randrange(2, 8)):
            at = base + rng.randrange(0, 200)
            claims.append((at, bytes([rng.randrange(256)]) * rng.randrange(1, 40)))
        rng.shuffle(claims)
        claims.insert(0, (base, claims[0][1] if claims else b"x"))
        got = only(capture([seg(at, data) for at, data in claims]))
        assert got.client.data == _model(claims, base), f"round {round_}"


def test_provenance_names_the_packet_that_actually_carried_the_octet():
    """Every octet in a reassembled direction is the octet the packet its
    provenance names had at that position."""
    pl = capture(
        [seg(20, b"ccc"), seg(14, b"aaa"), seg(17, b"bbb"), seg(14, b"ZZZ")]
    )
    s = only(pl)
    data = s.client.data
    for at, n, pkt in s.client.segments:
        payload = _payload(pl[pkt])
        assert payload.find(data[at : at + n]) >= 0
        assert s.client.packet_at(at) == pkt


def test_a_packet_carrying_two_messages_worth_of_octets_loses_neither():
    """A segment can end one message and begin another that never completes.
    Standing the first in for the whole packet used to take the second's
    octets out of the capture with nothing said about it."""
    head, tail = REQUEST[:10], b"GET /b HTTP/1.1\r\nCon"
    pl = capture([seg(1, head), seg(1 + len(head), REQUEST[10:] + tail)])
    out, kinds = pl._list.reassembled()
    blob = b"".join(bytes(p) for p in PacketList(out))
    assert REQUEST in blob
    assert tail in blob


def test_the_message_splice_cannot_outgrow_the_capture_without_a_bound():
    """One frame of headers per message, and a TLS record can be five octets,
    so the splice is the one part of reassembly that can outgrow its input.
    Past the bound the rest passes through as captured, losing nothing."""
    from wiry.stream import MAX_REFRAME_GROWTH

    empty = bytes([0x16, 0x03, 0x01, 0x00, 0x00])
    payload = empty * 280
    frames = [
        seg(1 + i * len(payload), payload, dport=443) for i in range(9000)
    ]
    pl = capture(frames)
    given = sum(len(bytes(p)) for p in frames)
    out, kinds = pl._list.reassembled()
    got = PacketList(out)
    built = sum(len(bytes(p)) for p, k in zip(got, kinds) if k == 1)
    # Unbounded, this capture frames to about 11x its own size; the ceiling is
    # the named growth plus the framing that keeps a part-consumed packet
    # whole, which is bounded by the packets themselves.
    assert built <= 2 * given + MAX_REFRAME_GROWTH
    assert kinds.count(0) > 0, "the bound never engaged, so it is untested"
    # Every octet of payload is still somewhere in the result.
    assert sum(len(bytes(p)) - 54 for p in got) == len(payload) * len(frames)
